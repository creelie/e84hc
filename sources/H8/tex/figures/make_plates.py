def fig_quadric():
    F = Plate("fig_quadric",
              "The spinor quadric at n = 2, d = 2 in the chart a = 1: the "
              "rational line P(P_t) is the axis, and its complex points form "
              "a sphere whose poles are [e^{+-st}].", "make_plates.py")
    d = float(D_Q)
    sd = math.sqrt(d)

    def rho(b):
        return math.sqrt(1.0 + b * b / d)

    # the equation, checked on the rulings and on the axis
    for t in (0.3, 1.9):
        for sg in (1, -1):
            for l in (-1.2, 0.4):
                x = math.cos(t) - l * math.sin(t)
                y = math.sin(t) + l * math.cos(t)
                b = sg * sd * l
                assert abs(d * (x * x + y * y) - b * b - d) < 1e-12
    # on the axis x = y = 0 the equation is b^2 = -d: no real point, and
    # the two complex points b = +-sqrt(-d) = +-s are u_t +- s v_t

    # ---------------------------------------------------------- panel (a)
    az, el, dist = math.radians(-64.0), math.radians(17.0), 15.0
    tgt = (0.0, 0.0, 0.05)
    eye = (dist * math.cos(el) * math.cos(az),
           dist * math.cos(el) * math.sin(az),
           tgt[2] + dist * math.sin(el))
    cam = Camera(eye=eye, target=tgt, focal=dist, scale=1.30)
    sc = Scene(cam, light=(0.35, -0.80, 0.72))
    # the cuts fall on grid lines of the mesh (144 facets round the waist)
