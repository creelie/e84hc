import render3d as _r3


class Mesh:
    """A parametric surface rendered through Scene.surface, with the depth of
    each of its facets kept, so that a curve lying on the surface can be
    sorted exactly after the facet it lies on."""

    def __init__(self, sc, f, urange, vrange, nu, nv, keep_uv=None, **kw):
        self.sc, self.f = sc, f
        self.u0, self.u1 = urange
        self.v0, self.v1 = vrange
        self.nu = int(round(nu * _r3.DETAIL)) if nu > 1 else nu
        self.nv = int(round(nv * _r3.DETAIL)) if nv > 1 else nv
        self.keep_uv = keep_uv
        cull = None
        if keep_uv is not None:
            du = (self.u1 - self.u0) / self.nu
            dv = (self.v1 - self.v0) / self.nv

            def cull(P, _k=[0]):
                # Scene.surface visits (i, j) in order
                i, j = divmod(_k[0], self.nv)
                _k[0] += 1
                return keep_uv(self.u0 + (i + 0.5) * du,
                               self.v0 + (j + 0.5) * dv)
        sc.surface(f, urange, vrange, nu, nv, cull=cull, **kw)

    def ij(self, u, v):
        i = int((u - self.u0) / (self.u1 - self.u0) * self.nu)
        j = int((v - self.v0) / (self.v1 - self.v0) * self.nv)
        return min(max(i, 0), self.nu - 1), min(max(j, 0), self.nv - 1)

    def depth(self, u, v):
        i, j = self.ij(u, v)
        us = [self.u0 + (self.u1 - self.u0) * (i + a) / self.nu
              for a in (0, 1)]
        vs = [self.v0 + (self.v1 - self.v0) * (j + b) / self.nv
              for b in (0, 1)]
        ds = [self.sc.cam.project(self.f(uu, vv))[1] for uu in us
              for vv in vs]
        return sum(ds) / 4.0

    def present(self, u, v):
        if self.keep_uv is None:
            return True
        i, j = self.ij(u, v)
        du = (self.u1 - self.u0) / self.nu
        dv = (self.v1 - self.v0) / self.nv
        return self.keep_uv(self.u0 + (i + 0.5) * du,
                            self.v0 + (j + 0.5) * dv)

    def curve(self, uv, trange, n, style, priority=1):
        """uv(t) -> (u, v); the curve f(uv(t)), piece by piece, each piece
        sorted just after the facet under its midpoint, and dropped where
        the facet is cut away."""
        t0, t1 = trange
        ps = [uv(t0 + (t1 - t0) * k / n) for k in range(n + 1)]
        run = []
        for k in range(n):
            (ua, va), (ub, vb) = ps[k], ps[k + 1]
            um, vm = (ua + ub) / 2, (va + vb) / 2
            if not self.present(um, vm):
                continue
            a, b = self.f(ua, va), self.f(ub, vb)
            (pa, _), (pb, _) = self.sc.cam.project(a), self.sc.cam.project(b)
            self.sc.add(self.depth(um, vm) - 1e-4,
                        "  \\draw[%s] (%.4f,%.4f) -- (%.4f,%.4f);\n"
                        % (style, pa[0], pa[1], pb[0], pb[1]), priority)


def silhouette_sphere(cam, centre, R, n=240):
    """The projected outline of a sphere under a perspective camera."""
    e = sub(cam.eye, centre)
    ne = norm(e)
    u = unit(e)
    h = R * R / ne
    rr = math.sqrt(max(0.0, R * R - h * h))
    b1 = unit(cross(u, (0.0, 0.0, 1.0)))
    b2 = cross(u, b1)
    out = []
    for k in range(n + 1):
        t = 2 * math.pi * k / n
        p = tuple(centre[i] + h * u[i] + rr * (math.cos(t) * b1[i]
                                               + math.sin(t) * b2[i])
                  for i in range(3))
        out.append(cam.project(p)[0])
    return out


def seal(body, lw=0.25):
    """Stroke every opaque facet in its own colour, so that the hairline
    seams between adjacent facets do not show in a raster of the page."""
    return re.sub(r"\\path\[draw=none,fill=([^\],]+)\]",
                  lambda m: "\\path[draw=%s,line width=%.2fpt,fill=%s]"
                  % (m.group(1), lw, m.group(1)), body)


def visible_runs(pts, hidden):
    """Split a sampled curve into its maximal runs of visible samples."""
    runs, cur = [], []
    for p in pts:
        if not hidden(p):
            cur.append(p)
        else:
            if len(cur) > 1:
                runs.append(cur)
            cur = []
    if len(cur) > 1:
        runs.append(cur)
    return runs


def ray_hits_quadric(eye, p, coef, accept):
    """Does the open segment from eye to p meet the quadric
    c0 x^2 + c1 y^2 + c2 z^2 + c3 = 0 at a point q with accept(q)?"""
    w = sub(p, eye)
    c0, c1, c2, c3 = coef
    A = c0 * w[0] ** 2 + c1 * w[1] ** 2 + c2 * w[2] ** 2
    B = 2 * (c0 * eye[0] * w[0] + c1 * eye[1] * w[1] + c2 * eye[2] * w[2])
    C = c0 * eye[0] ** 2 + c1 * eye[1] ** 2 + c2 * eye[2] ** 2 + c3
    if abs(A) < 1e-14:
        roots = [] if abs(B) < 1e-14 else [-C / B]
    else:
        disc = B * B - 4 * A * C
        if disc < 0:
            return False
        r = math.sqrt(disc)
        roots = [(-B - r) / (2 * A), (-B + r) / (2 * A)]
    for t in roots:
        if 1e-6 < t < 1 - 2e-5:
            q = addv(eye, smul(t, w))
            if accept(q):
                return True
    return False


