def seg_cross(p, q, r, s):
    """True if the closed segments pq and rs meet."""
    def orient(a, b, c):
        v = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
        return 0 if abs(v) < 1e-12 else (1 if v > 0 else -1)
    o1, o2 = orient(p, q, r), orient(p, q, s)
    o3, o4 = orient(r, s, p), orient(r, s, q)
    if o1 != o2 and o3 != o4:
        return True
    return False


def shift_tikz(s, dx, dy):
    """Translate every coordinate pair of a TikZ fragment."""
    return COORD.sub(lambda m: "(%.4f,%.4f)" % (float(m.group(1)) + dx,
                                                float(m.group(2)) + dy), s)


def extent(s):
    xs, ys = [], []
    for a, b in COORD.findall(s):
        xs.append(float(a))
        ys.append(float(b))
    return min(xs), min(ys), max(xs), max(ys)


class Grid:
    """A spatial hash of strokes and fills, for fast exact tests."""

    def __init__(self, cell=0.35):
        self.cell = cell
        self.bins = {}

    def _keys(self, bb):
        c = self.cell
        for i in range(int(math.floor(bb[0] / c)),
                       int(math.floor(bb[2] / c)) + 1):
            for j in range(int(math.floor(bb[1] / c)),
                           int(math.floor(bb[3] / c)) + 1):
                yield (i, j)

    def add(self, item, bb):
        for k in self._keys(bb):
            self.bins.setdefault(k, []).append(item)

    def query(self, bb):
        seen, out = set(), []
        for k in self._keys(bb):
            for it in self.bins.get(k, ()):
                if id(it) not in seen:
                    seen.add(id(it))
                    out.append(it)
        return out


ANCHOR_OF = {"W": "west", "E": "east", "N": "north", "S": "south",
             "C": None}


class Plate(Fig):
    """Fig with a placer for labels with leaders.  request() queues a label;
    solve() places every queued label in order."""

    def __init__(self, name, blurb, gen, preamble=""):
        Fig.__init__(self, name, blurb, pad=0.05)
        self.gen = gen
        self.preamble = preamble
        self.requests = []
        self.dots = []             # (x, y, r): marked points, kept clear
        self.frame = None          # optional (x0, y0, x1, y1) for labels

    # -- marked points -----------------------------------------------------
    def mark(self, x, y, r=0.055, fill="PInk", draw="white", lw=0.5,
             tag="dot"):
        self.raw(r"  \filldraw[fill=%s,draw=%s,line width=%.2fpt] "
                 r"(%.3f,%.3f) circle (%.3f);" % (fill, draw, lw, x, y, r))
        self.polys.append((circle_pts(x, y, r + 0.01), tag))
        self.dots.append((x, y, r))

    def hollow(self, x, y, r=0.06, draw="PInk", lw=0.8, tag="dot",
               style=""):
        self.raw(r"  \filldraw[fill=white,draw=%s,line width=%.2fpt%s] "
                 r"(%.3f,%.3f) circle (%.3f);" % (draw, lw, style, x, y, r))
        self.polys.append((circle_pts(x, y, r + 0.01), tag))
        self.dots.append((x, y, r))

    # -- queued labels -------------------------------------------------------
    def request(self, anchor, text, color="PInk", size=SM, tag=None,
                allow=(), prefer=None, spread=180.0, rmin=0.16, rmax=3.2,
                sides="WENS", leader="PSlate!80", clear=0.0, lw=0.4,
                region=None, weight=1.0):
        """anchor: the point (in figure cm) the label names.  prefer: the
        preferred direction in degrees; spread: how far from it to look.
        clear: the radius of the marked point at the anchor, so the leader
        starts on its rim."""
        if tag is None:
            tag = "L%d" % len(self.requests)
        self.requests.append(dict(anchor=anchor, text=text, color=color,
                                  size=size, tag=tag, allow=set(allow),
                                  prefer=prefer, spread=spread, rmin=rmin,
                                  rmax=rmax, sides=sides, leader=leader,
                                  clear=clear, lw=lw, region=region,
                                  weight=weight))
        return tag

    @staticmethod
    def opts(color, size, side):
        o = "text=%s,inner sep=1pt,align=center,font=%s" % (color, size)
        a = ANCHOR_OF[side]
        if a:
            o += ",anchor=%s" % a
        return o

    def _grid(self):
        G = Grid()
        for p, q, tag in self.segs:
            G.add(("s", p, q, tag), (min(p[0], q[0]), min(p[1], q[1]),
                                     max(p[0], q[0]), max(p[1], q[1])))
        for pts, tag in self.polys:
            xs = [a for a, b in pts]
            ys = [b for a, b in pts]
            G.add(("p", pts, tag), (min(xs), min(ys), max(xs), max(ys)))
        return G

    def solve(self, verbose=False):
        if not self.requests:
            return
        # boxes of every text, anchored at the centre, in one run of TeX
        specs = [(self.opts(r["color"], r["size"], "C"), r["text"])
                 for r in self.requests]
        fixed = [(l["opts"], l["text"]) for l in self.labels]
        self.premeasure(specs + fixed)
        for l in self.labels:
            b = self._cache[(l["opts"], l["text"])]
            l["box"] = (l["x"] + b[0], l["y"] + b[1], l["x"] + b[2],
                        l["y"] + b[3])
        G = self._grid()
        placed = [dict(box=l["box"], crude=self._crude(l["opts"], l["x"],
                                                       l["y"], l["text"]))
                  for l in self.labels]
        leaders = []
        for r in self.requests:
            best = self._place(r, G, placed, leaders)
            if best is None:
                if os.environ.get("PLATE_DEBUG"):
                    print("   UNPLACED", r["text"])
                    continue
                raise SystemExit("%s: no place for label %r"
                                 % (self.name, r["text"]))
            score, (x, y), side, box, lead = best
            if lead is not None:
                self.path(lead, r["leader"], lw=r["lw"], tag=r["tag"])
                p, q = lead
                G.add(("s", p, q, r["tag"]),
                      (min(p[0], q[0]), min(p[1], q[1]),
                       max(p[0], q[0]), max(p[1], q[1])))
                leaders.append((p, q, r["tag"]))
            opts = self.opts(r["color"], r["size"], side)
            self.node(x, y, r["text"], opts, tag=r["tag"],
                      allow=r["allow"])
            G.add(("p", [(box[0], box[1]), (box[2], box[1]),
                         (box[2], box[3]), (box[0], box[3])], "label"), box)
            placed.append(dict(box=box, crude=self._crude(opts, x, y,
                                                          r["text"])))
            if verbose:
                print("   placed %-40s score %.2f" % (r["text"][:40], score))

    @staticmethod
    def _crude(opts, x, y, text):
        b = checkfigs.box(opts, x, y, text)
        return b[:4]

    def _place(self, r, G, placed, leaders):
        w0 = self._cache[(self.opts(r["color"], r["size"], "C"), r["text"])]
        W, H = w0[2] - w0[0], w0[3] - w0[1]
        ax, ay = r["anchor"]
        P = self.pad + 0.02
        best = None
        radii = [r["rmin"]] + [x for x in (0.30, 0.42, 0.55, 0.70, 0.85,
                                            1.0, 1.2, 1.4, 1.65, 1.9, 2.2,
                                            2.5, 2.85, 3.2, 3.6, 4.0)
                               if r["rmin"] < x <= r["rmax"]]
        for rad in radii:
            for k in range(48):
                th = 7.5 * k
                if r["prefer"] is not None:
                    dev = abs((th - r["prefer"] + 180.0) % 360.0 - 180.0)
                    if dev > r["spread"]:
                        continue
                else:
                    dev = 0.0
                c, s = math.cos(math.radians(th)), math.sin(math.radians(th))
                ex, ey = ax + rad * c, ay + rad * s
                if abs(c) >= 0.5:
                    side = "W" if c > 0 else "E"
                else:
                    side = "S" if s > 0 else "N"
                if side not in r["sides"]:
                    continue
                if side == "W":
                    box = (ex, ey - H / 2, ex + W, ey + H / 2)
                elif side == "E":
                    box = (ex - W, ey - H / 2, ex, ey + H / 2)
                elif side == "S":
                    box = (ex - W / 2, ey, ex + W / 2, ey + H)
                else:
                    box = (ex - W / 2, ey - H, ex + W / 2, ey)
                if r["region"] is not None:
                    R = r["region"]
                    if (box[0] < R[0] or box[1] < R[1] or box[2] > R[2]
                            or box[3] > R[3]):
                        continue
                pbox = (box[0] - P, box[1] - P, box[2] + P, box[3] + P)
                if any(rects_meet(pbox, q["box"]) for q in placed):
                    continue
                opts = self.opts(r["color"], r["size"], side)
                cb = self._crude(opts, ex, ey, r["text"])
                if any(rects_meet(cb, q["crude"]) for q in placed):
                    continue
                if any(math.hypot(min(max(dx, pbox[0]), pbox[2]) - dx,
                                  min(max(dy, pbox[1]), pbox[3]) - dy)
                       < dr + 0.04 for dx, dy, dr in self.dots):
                    continue
                bad = False
                for it in G.query(pbox):
                    if it[0] == "s":
                        if it[3] in r["allow"] or it[3] == r["tag"]:
                            continue
                        if seg_hits_rect(it[1], it[2], pbox):
                            bad = True
                            break
                    else:
                        if it[2] in r["allow"] or it[2] == "bg":
                            continue
                        if poly_hits_rect(it[1], pbox):
                            bad = True
                            break
                if bad:
                    continue
                # the leader, from the rim of the anchor to the label
                lead = None
                cross_pen = 0.0
                if rad > 0.26:
                    st = (ax + (r["clear"] + 0.035) * c,
                          ay + (r["clear"] + 0.035) * s)
                    en = (ex - 0.035 * c, ey - 0.035 * s)
                    lead = (st, en)
                    lb = (min(st[0], en[0]), min(st[1], en[1]),
                          max(st[0], en[0]), max(st[1], en[1]))
                    for q in placed:
                        if seg_hits_rect(st, en, q["box"]):
                            bad = True
                            break
                    if bad:
                        continue
                    if any(seg_cross(st, en, p, q) for p, q, t in leaders):
                        continue
                    n = 0
                    for it in G.query(lb):
                        if it[0] == "s" and it[3] != "label" and \
                                seg_cross(st, en, it[1], it[2]):
                            n += 1
                    cross_pen = 0.05 * n
                score = r["weight"] * rad + 0.004 * dev + cross_pen
                if best is None or score < best[0]:
                    best = (score, (ex, ey), side, box, lead)
            if best is not None and best[0] < rad * r["weight"] * 0.8:
                break
        return best

    # -- output ----------------------------------------------------------------
    def write(self):
        bad = self.check(verbose=True)
        if bad and not os.environ.get("PLATE_DEBUG"):
            raise SystemExit("%s: %d problems" % (self.name, len(bad)))
        # the crude estimate of checkfigs.py as well
        boxes = [checkfigs.box(l["opts"], l["x"], l["y"], l["text"])
                 for l in self.labels
                 if checkfigs._plain(l["text"]).strip()]
        hits = [(a[4], b[4]) for i, a in enumerate(boxes)
                for b in boxes[i + 1:] if rects_meet(a[:4], b[:4])]
        if hits and not os.environ.get("PLATE_DEBUG"):
            raise SystemExit("%s: checkfigs estimate overlaps %s"
                             % (self.name, hits))
        path = os.path.join(HERE, self.name + ".tex")
        with open(path, "w") as f:
            f.write(HEAD.format(name=self.name, gen=self.gen,
                                blurb=self.blurb, preamble=self.preamble))
            f.write(self.tikz())
            f.write(TAIL)
        print("wrote %s: %d labels" % (path, len(self.labels)))


