def fig_fibres():
    F = Plate("fig_fibres",
              "Lemma lem:annihilator at n = 3: the basis of wedge^2 H^{0,1} "
              "in three blocks, the mixed block the kernel of multiplication "
              "by omega; and the three dimensions for n = 2, ..., 6.",
              "make_plates.py")
    n = 3
    N = 2 * n
    c = 0.60
    X0, Y0 = 1.30, 7.50
    names = [r"u_{%d}" % (k + 1) for k in range(n)] + \
            [r"v_{%d}" % (k + 1) for k in range(n)]
    COL = {"++": "PIndigo", "+-": "PAmber", "--": "PMag"}

    def block(i, j):
        if j < n:
            return "++"
        if i < n:
            return "+-"
        return "--"
    count = {"++": 0, "+-": 0, "--": 0}
    for i in range(N):
        for j in range(N):
            x, y = X0 + j * c, Y0 - (i + 1) * c
            if i < j:
                b = block(i, j)
                count[b] += 1
                F.rect(x, y, x + c, y + c, "%s!%d" % (COL[b], 30 if b != "+-"
                                                      else 40),
                       tag=b, draw="white", lw=0.8)
            else:
                F.rect(x, y, x + c, y + c, "WSlate!55", tag="lower",
                       draw="white", lw=0.8)
    assert count == {"++": math.comb(n, 2), "+-": n * n,
                     "--": math.comb(n, 2)}
    # the outlines of the three blocks
    def outline(cells, col):
        edges = {}
        for i, j in cells:
            x, y = X0 + j * c, Y0 - (i + 1) * c
            for e in (((x, y), (x + c, y)), ((x + c, y), (x + c, y + c)),
                      ((x, y + c), (x + c, y + c)), ((x, y), (x, y + c))):
                k = tuple(sorted((round(a[0], 6), round(a[1], 6))
                                 for a in e))
                edges[k] = edges.get(k, 0) + 1
        for (p, q), m in edges.items():
            if m == 1:
                F.path([p, q], col, lw=1.1, tag="outline")
    for b in COL:
        outline([(i, j) for i in range(N) for j in range(N)
                 if i < j and block(i, j) == b], COL[b])
    # row and column names
    for k in range(N):
        F.text(X0 + (k + 0.5) * c, Y0 + 0.17, r"$%s$" % names[k], "PInk", FS,
               anchor="south", tag="names")
        F.text(X0 - 0.10, Y0 - (k + 0.5) * c, r"$%s$" % names[k], "PInk", FS,
               anchor="east", tag="names")
    # braces for V_+^{0,1} and V_-^{0,1}
    def hbrace(xa, xb, y, text, col):
        F.raw(r"  \draw[%s,line width=0.6pt,decorate,decoration={brace,"
              r"amplitude=3.2pt}] (%.3f,%.3f) -- (%.3f,%.3f);"
              % (col, xa, y, xb, y))
        F.segs.append(((xa, y), (xb, y + 0.13), "brace"))
        F.text((xa + xb) / 2, y + 0.19, text, col, FS, anchor="south",
               tag="bracename")

    def vbrace(x, ya, yb, text, col, side="L"):
        if side == "L":
            F.raw(r"  \draw[%s,line width=0.6pt,decorate,decoration={brace,"
                  r"amplitude=3.2pt}] (%.3f,%.3f) -- (%.3f,%.3f);"
                  % (col, x, ya, x, yb))
            F.segs.append(((x - 0.13, ya), (x, yb), "brace"))
            F.text(x - 0.19, (ya + yb) / 2, text, col, FS, anchor="east",
                   tag="bracename")
        else:
            F.raw(r"  \draw[%s,line width=0.6pt,decorate,decoration={brace,"
                  r"amplitude=3.2pt,mirror}] (%.3f,%.3f) -- (%.3f,%.3f);"
                  % (col, x, ya, x, yb))
            F.segs.append(((x, ya), (x + 0.13, yb), "brace"))
            F.text(x + 0.19, (ya + yb) / 2, text, col, FS, anchor="west",
                   tag="bracename")
    yb = Y0 + 0.52
    hbrace(X0 + 0.03, X0 + n * c - 0.03, yb, r"$V_{+}^{0,1}$", "PInk")
    hbrace(X0 + n * c + 0.03, X0 + N * c - 0.03, yb, r"$V_{-}^{0,1}$",
           "PInk")
    xb = X0 - 0.62
    vbrace(xb, Y0 - n * c + 0.03, Y0 - 0.03, r"$V_{+}^{0,1}$", "PInk")
    vbrace(xb, Y0 - N * c + 0.03, Y0 - n * c - 0.03, r"$V_{-}^{0,1}$",
           "PInk")
    # the dimensions, inside the blocks
    F.text(X0 + 2.5 * c, Y0 - 0.5 * c, r"$3$", "PIndigo!80!black", SM,
           allow=("++",), tag="dim")
    F.text(X0 + 4.5 * c, Y0 - 1.5 * c, r"$9$", "PAmber!70!black", SM,
           allow=("+-",), tag="dim")
    F.text(X0 + 5.5 * c, Y0 - 3.5 * c, r"$3$", "PMag!80!black", SM,
           allow=("--",), tag="dim")
    # the kernel of multiplication by omega: a brace on the right
    vbrace(X0 + N * c + 0.10, Y0 - n * c + 0.03, Y0 - 0.03,
           r"$\ker(\,\cdot\,\omega)$", "PAmber!80!black", side="R")
    YA0 = Y0 - N * c

    # ---------------------------------------------------------- panel (b)
    rows = list(range(2, 7))
    unit_ = 0.075
    rh = 0.42
    bx0 = 1.00
    by1 = YA0 - 1.30
    for k, m in enumerate(rows):
        y = by1 - k * rh
        a, b = math.comb(m, 2), m * m
        assert 2 * a + b == math.comb(2 * m, 2)
        x = bx0
        for v, col in ((a, "PIndigo!45"), (b, "PAmber!55"), (a, "PMag!40")):
            F.rect(x, y - 0.12, x + v * unit_, y + 0.12, col, tag="bar",
                   draw="white", lw=0.5)
            x += v * unit_
        F.text(bx0 - 0.12, y, r"$%d$" % m, "PInk", FS, anchor="east",
               tag="rowname")
        F.text(x + 0.10, y, r"$%d$" % math.comb(2 * m, 2), "PInk", FS,
               anchor="west", tag="rowval")
        F.text(bx0 + (a + b / 2) * unit_, y, r"$%d$" % b,
               "PAmber!40!black", FS, allow=("bar",), tag="inbar") \
            if b * unit_ > 0.28 else None
    F.text(bx0 - 0.12, by1 + 0.46, r"$n$", "PInk", FS, anchor="east",
           tag="rowname")
    F.text(bx0, by1 + 0.46,
           r"$\binom{2n}{2}=\textcolor{PIndigo}{\binom{n}{2}}"
           r"+\textcolor{PAmber!85!black}{n^{2}}"
           r"+\textcolor{PMag}{\binom{n}{2}}$", "PInk", FS, anchor="west",
           tag="rowname")
    F.text(0.0, Y0 + 1.20, r"\textup{(a)}", "PInk", SM, anchor="north west",
           tag="letter")
    F.text(0.0, by1 + 1.02, r"\textup{(b)}", "PInk", SM,
           anchor="north west", tag="letter")
    return F


