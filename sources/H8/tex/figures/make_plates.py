def slopes(H):
    """The rational slopes p/q of height max(|p|, q) <= H, with their
    heights, and the slope infinity = 1/0 of height one."""
    out = {}
    for q in range(0, H + 1):
        for p in range(-H, H + 1):
            if (p, q) == (0, 0) or math.gcd(p, q) != 1:
                continue
            if q == 0 and p != 1:
                continue
            lam = math.inf if q == 0 else p / q
            h = max(abs(p), q)
            if lam not in out or out[lam][0] > h:
                out[lam] = (h, p, q)
    return out


