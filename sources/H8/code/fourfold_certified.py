# the configuration of prop:fourfoldrank

def rfr(rng):
    return Fr(rng.randrange(2 ** 12), 2 ** 12)


class Config:
    def __init__(self, p, t1, t2, t3, rng):
        self.p, self.t, self.rng = p, (t1, t2, t3), rng
        self.M = [{t: Piece([[t, 0], [0, t]], [rfr(rng) for _ in range(4)])
                   for t in (t1, t2, t3)} for _ in range(3)]
        self.Lvals, self.surf = {}, {}

    def L(self, zj, j):
        key = (zj, j)
        if key not in self.Lvals:
            self.Lvals[key] = [rfr(self.rng) for _ in range(4)]
        z = complex(zj)
        return Piece([[self.p, z], [z.conjugate(), self.p]], self.Lvals[key])

    def surface(self, zj, j):
        key = (zj, j)
        if key in self.surf:
            return self.surf[key]
        rng = self.rng
        t1, t2, t3 = self.t
        M1, M2, M3 = self.M[j][t1], self.M[j][t2], self.M[j][t3]
        L = self.L(zj, j)
        C = Cover(zj)
        homs = {'S': Hom(M2, M3), 'Om': Hom(L, M3), 'U': Hom(L, M1),
                'E': Hom(L, M2), 'Phi': Hom(M1, M2), 'Q': Hom(M1, M3)}
        bund = {k: C.bundles(h) for k, h in homs.items()}
        ops, coef0 = [], []
        for c in (0, 1):
            o, c0, _ = curve_ops(*(bund[k][c] for k in
                                   ('S', 'Om', 'U', 'E', 'Phi')), rng)
            ops.append(o)
            coef0.append(c0)
        Q = [q_tensor(bund['Om'][c], bund['U'][c], bund['Q'][c], rng)
             for c in (0, 1)]
        proj, rel, dims = {}, True, True
        for k in ('Om', 'U'):
            P, r, dm = projector(C, homs[k], *bund[k], rng)
            proj[k] = P
            rel &= r
            dims &= dm
        Zc = zpull(C, homs['Phi'], t2 - t1, *bund['Phi'], rng)
        Sc = zpull(C, homs['S'], t3 - t2, *bund['S'], rng)
        dSu, dSv = bund['S'][0].d, bund['S'][1].d
        X1 = [[Sc[a * dSv + b, 0] for b in range(dSv)] for a in range(dSu)]
        sd = dict(ops=ops, coef0=coef0, Q=Q, proj=proj, Zc=Zc, X1=X1,
                  bund=bund, rel=rel, dims=dims)
        self.surf[key] = sd
        return sd


def rvec_proj(rng, P, conj=False):
    """P c (or conj(P) c) for a random rational vector c."""
    n = P.nrows()
    c = acb_mat([[acb(fa(Fr(rng.randrange(-2 ** 10, 2 ** 10), 2 ** 10)),
                      fa(Fr(rng.randrange(-2 ** 10, 2 ** 10), 2 ** 10)))]
                 for _ in range(n)])
    M = P.conjugate() if conj else P
    return M * c


def as_matrix(vec, r, c):
    return [[vec[i * c + j, 0] for j in range(c)] for i in range(r)]


def surfvec(sd, X1, x2, X3, opu, opv):
    """T[w, v] = sum X1[a,b] x2[c,e] X3[f,g] op_u[a][c][f][w] op_v[b][e][g][v],
    paired with the pulled-back theta basis of Hom(M1, M2) on B_j."""
    Ou, Ov = sd['ops'][0][opu], sd['ops'][1][opv]
    dSu, dOu, dUu, dPu = len(Ou), len(Ou[0]), len(Ou[0][0]), len(Ou[0][0][0])
    dSv, dOv, dUv, dPv = len(Ov), len(Ov[0]), len(Ov[0][0]), len(Ov[0][0][0])
    Ut = acb_mat([[Ou[a][c][f][w] for a in range(dSu) for c in range(dOu)
                   for f in range(dUu)] for w in range(dPu)])
    Vm = acb_mat([[Ov[b][e][g][v] for v in range(dPv)] for b in range(dSv)
                  for e in range(dOv) for g in range(dUv)])
    K = acb_mat(dSu * dOu * dUu, dSv * dOv * dUv)
    for a in range(dSu):
        for c in range(dOu):
            for f in range(dUu):
                row = (a * dOu + c) * dUu + f
                for b in range(dSv):
                    x1 = X1[a][b]
                    for e in range(dOv):
                        y = x1 * x2[c][e]
                        for g in range(dUv):
                            K[row, (b * dOv + e) * dUv + g] = y * X3[f][g]
    T = Ut * K * Vm
    flat = acb_mat(1, dPu * dPv)
    for w in range(dPu):
        for v in range(dPv):
            flat[0, w * dPv + v] = T[w, v]
    return flat * sd['Zc']


def right_sign():
    mu4 = [1, 1j, -1, -1j]
    out = []
    for z in itertools.product(range(4), repeat=3):
        if sum(z) % 4 == 0:
            out.append(tuple(mu4[k] for k in z))
    return out


def _midpoints(M):
    """The midpoints of an acb matrix as a complex numpy array."""
    import numpy as np
    return np.array([[complex(float(M[i, j].real.mid()),
                              float(M[i, j].imag.mid()))
                      for j in range(M.ncols())] for i in range(M.nrows())])


def _pivots(mid, rank):
    """Sorted indices of `rank` columns of a complex array chosen by QR with
    column pivoting (Businger-Golub): take the column of largest residual
    norm and project it out of the others, rank times.  Only the choice of
    columns uses floating point; the minor they give is certified in balls."""
    import numpy as np
    res = mid.copy()
    piv = []
    for _ in range(rank):
        norms = (np.abs(res) ** 2).sum(axis=0)
        norms[piv] = -1.0
        j = int(np.argmax(norms))
        piv.append(j)
        q = res[:, j] / np.linalg.norm(res[:, j])
        res = res - np.outer(q, q.conj() @ res)
    return sorted(piv)


def kernel_vectors(Lm, rank):
    """Balls containing exact vectors spanning the kernel of a matrix of
    exact rank `rank` (the rank is at most `rank` by theory; a nonsingular
    minor of that size is certified here)."""
    mid = _midpoints(Lm)
    cols = _pivots(mid, rank)
    rows = _pivots(mid[:, cols].T, rank)
    A = acb_mat([[Lm[i, j] for j in cols] for i in rows])
    free = [j for j in range(Lm.ncols()) if j not in cols]
    out = []
    for f in free:
        b = acb_mat([[Lm[i, f]] for i in rows])
        x = A.solve(b)
        v = acb_mat(Lm.ncols(), 1)
        v[f, 0] = acb(1)
        for t, j in enumerate(cols):
            v[j, 0] = -x[t, 0]
        out.append(v)
    return out


def contract_m1(X1, coef0u, coef0v):
    """m1[(c,e),(g,h)] = sum_ab X1[a][b] coef0_u[a][c][g] coef0_v[b][e][h]."""
    dSu, dOu, dEu = len(coef0u), len(coef0u[0]), len(coef0u[0][0])
    dSv, dOv, dEv = len(coef0v), len(coef0v[0]), len(coef0v[0][0])
    out = acb_mat(dOu * dOv, dEu * dEv)
    for c in range(dOu):
        for e in range(dOv):
            for g in range(dEu):
                for h in range(dEv):
                    s = acb(0)
                    for a in range(dSu):
                        for b in range(dSv):
                            s += X1[a][b] * coef0u[a][c][g] * coef0v[b][e][h]
                    out[c * dOv + e, g * dEv + h] = s
    return out


def contract_m2(X3, Qu, Qv):
    """m2[(c,e),(m,n)] = sum_fg X3[f][g] Q_u[c][f][m] Q_v[e][g][n]."""
    dOu, dUu, dQu = len(Qu), len(Qu[0]), len(Qu[0][0])
    dOv, dUv, dQv = len(Qv), len(Qv[0]), len(Qv[0][0])
    out = acb_mat(dOu * dOv, dQu * dQv)
    for c in range(dOu):
        for e in range(dOv):
            for m in range(dQu):
                for n in range(dQv):
                    s = acb(0)
                    for f in range(dUu):
                        for g in range(dUv):
                            s += X3[f][g] * Qu[c][f][m] * Qv[e][g][n]
                    out[c * dOv + e, m * dQv + n] = s
    return out


def basis_of_image(P, rank):
    """Columns of P spanning its image (rank certified by a minor)."""
    cols = _pivots(_midpoints(P), rank)
    B = acb_mat([[P[i, j] for j in cols] for i in range(P.nrows())])
    return B


def columns(cfg, zeta, rng, mc=False, sign=-1, info=None):
    sds = [cfg.surface(zeta[j], j) for j in range(3)]
    X1 = [sd['X1'] for sd in sds]
    X3, x2opts = [], []
    for m, sd in enumerate(sds):
        bU, bO = sd['bund']['U'], sd['bund']['Om']
        x3 = rvec_proj(rng, sd['proj']['U'])
        X3.append(as_matrix(x3, bU[0].d, bU[1].d))
        x2opts.append(None)
    terms = []
    if mc:
        K1, K2, Vy = [], [], []
        for m, sd in enumerate(sds):
            bO = sd['bund']['Om']
            nOm = abs(Hom(cfg.L(zeta[m], m), cfg.M[m][cfg.t[2]]).det())
            nE = abs(Hom(cfg.L(zeta[m], m), cfg.M[m][cfg.t[1]]).det())
            nM1M3 = abs(Hom(cfg.M[m][cfg.t[0]], cfg.M[m][cfg.t[2]]).det())
            B = basis_of_image(sd['proj']['Om'].conjugate(), nOm)
            m1 = contract_m1(X1[m], sd['coef0'][0], sd['coef0'][1])
            m2 = contract_m2(X3[m], sd['Q'][0], sd['Q'][1])
            L1 = m1.transpose() * B
            L2 = m2.transpose() * B
            k1 = [B * v for v in kernel_vectors(L1, nE)]
            k2 = [B * v for v in kernel_vectors(L2, nM1M3)]
            if info is not None:
                info.append((len(k1), len(k2)))
            K1.append(k1)
            K2.append(k2)
            Vy.append(B)
        for j, jp in itertools.permutations(range(3), 2):
            for _ in range(2):
                fac = []
                for m in range(3):
                    if m == j:
                        pool = K1[m]
                    elif m == jp:
                        pool = K2[m]
                    else:
                        pool = None
                    if pool is None:
                        v = rvec_proj(rng, sds[m]['proj']['Om'], conj=True)
                    else:
                        v = acb_mat(pool[0].nrows(), 1)
                        for vec in pool:
                            c = acb(fa(Fr(rng.randrange(-2 ** 10, 2 ** 10),
                                          2 ** 10)))
                            v = v + vec * c
                    fac.append(v)
                terms.append(fac)
        if info is not None:
            # x1 x2 = 0 and x2 x3 = 0 hold on the kernel vectors: the
            # images are balls containing 0
            ok = True
            for m in range(3):
                m1 = contract_m1(X1[m], sds[m]['coef0'][0],
                                 sds[m]['coef0'][1])
                m2 = contract_m2(X3[m], sds[m]['Q'][0], sds[m]['Q'][1])
                for v in K1[m]:
                    ok &= (m1.transpose() * v).contains(
                        acb_mat(m1.ncols(), 1))
                for v in K2[m]:
                    ok &= (m2.transpose() * v).contains(
                        acb_mat(m2.ncols(), 1))
            info.append(('zero products', ok))
    else:
        terms.append([rvec_proj(rng, sd['proj']['Om'], conj=True)
                      for sd in sds])
    terms = [[as_matrix(f, sds[m]['bund']['Om'][0].d,
                        sds[m]['bund']['Om'][1].d)
              for m, f in enumerate(fac)] for fac in terms]
    cache = {}

    def sv(m, opu, opv, r):
        key = (m, opu, opv, r)
        if key not in cache:
            cache[key] = surfvec(sds[m], X1[m], terms[r][m], X3[m], opu, opv)
        return cache[key]

    def tensor(assign):
        tot = acb_mat(1, 729)
        for r in range(len(terms)):
            vs = [sv(m, assign.get(2 * m, 'Cup'), assign.get(2 * m + 1, 'Cup'),
                     r) for m in range(3)]
            t = acb_mat(1, 729)
            for a in range(9):
                for b in range(9):
                    ab = vs[0][0, a] * vs[1][0, b]
                    for c in range(9):
                        t[0, (a * 9 + b) * 9 + c] = ab * vs[2][0, c]
            tot = tot + t
        return tot
    de = [sds[c // 2]['bund']['E'][c % 2].d for c in range(6)]
    du = [sds[c // 2]['bund']['U'][c % 2].d for c in range(6)]
    cols = []
    for a, b in [(a, b) for a in range(6) for b in range(a + 1, 6)
                 if a // 2 != b // 2]:
        den = PI * (du[a] + du[b])
        out = acb_mat(1, 729)
        for M in (0, 1):
            kA = (PI * de[b]).sqrt() / (PI * (de[a] * M + de[b]) * den)
            kB = (PI * de[a]).sqrt() / (PI * (de[a] + de[b] * M) * den)
            out = out + tensor({a: 'F%d' % M, b: 'Dn'}) * acb(kA) \
                + tensor({a: 'Dn', b: 'F%d' % M}) * acb(sign * kB)
        cols.append(out)
    A = acb_mat(729, len(cols))
    for j, col in enumerate(cols):
        for i in range(729):
            A[i, j] = col[0, i]
    return A, sds


def certified_rank(A):
    """True if the Gram determinant of the columns of A is a ball excluding
    0, which proves that the exact matrix has full column rank."""
    G = A.conjugate().transpose() * A
    det = G.det()
    return not det.contains(0), det


def singular_ratio(A):
    import numpy as np
    mid = np.array([[complex(float(A[i, j].real.mid()),
                             float(A[i, j].imag.mid()))
                     for j in range(A.ncols())] for i in range(A.nrows())])
    s = np.linalg.svd(mid, compute_uv=False)
    return s[-1] / s[0], max(float(A[i, j].rad()) for i in range(A.nrows())
                              for j in range(A.ncols())) / s[0]


def total(params, seed, mc=False, sign=-1, info=None):
    rng = random.Random(seed)
    cfg = Config(*params, rng)
    blocks, per = [], []
    for zeta in right_sign():
        B, sds = columns(cfg, zeta, rng, mc=mc, sign=sign, info=info)
        blocks.append(B)
        per.append(certified_rank(B)[0])
    A = acb_mat(729, 12 * len(blocks))
    for k, B in enumerate(blocks):
        for i in range(729):
            for j in range(12):
                A[i, 12 * k + j] = B[i, j]
    ok, det = certified_rank(A)
    rel = all(sd['rel'] and sd['dims'] for sd in cfg.surf.values())
    return ok, per, rel, singular_ratio(A), len(cfg.surf)


