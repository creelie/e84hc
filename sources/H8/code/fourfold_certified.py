def part_H_levels():
    """The decomposition into levels against the quadrature of item (LXXII)."""
    import numpy as np
    import fourfold_products as fp
    rng = random.Random(5)
    cfg = Config(0, 2, 5, 6, rng)
    sd = cfg.surface(1j, 0)
    worst = 0.0
    for c in (0, 1):
        bs = [sd['bund'][k][c] for k in ('S', 'Om', 'U', 'E', 'Phi')]
        fb = [fp.Bundle(b.d, *b.floats()) for b in bs]
        fo = fp.CurveOps(*fb, fp.Grid(64))
        for key in ('Cup', 'Dn', 'F0', 'F1'):
            X = fo.op(key)
            Y = sd['ops'][c][key]
            Ym = np.array([[[[complex(float(Y[s][o][u][w].real.mid()),
                                      float(Y[s][o][u][w].imag.mid()))
                              for w in range(len(Y[0][0][0]))]
                             for u in range(len(Y[0][0]))]
                            for o in range(len(Y[0]))]
                           for s in range(len(Y))])
            worst = max(worst, np.abs(X - Ym).max() / np.abs(X).max())
    check("(H) the levels of products by interpolation agree with the "
          "quadrature of item (LXXII) on both curves", worst < 1e-11,
          "relative difference %.1e" % worst)


