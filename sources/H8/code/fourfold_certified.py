# 2. the per-curve maps of item (LXXII), by the decomposition into levels

def curve_ops(bS, bOm, bU, bE, bPhi, rng):
    """The tensors Cup, Dn, F0, F1 of item (LXXII) (CurveOps there) and the
    tensor coef0, as exact balls.  Returned as nested lists [s][o][u][w]
    (and coef0 as [s][o][g])."""
    dS, dO, dU, dE, dP = bS.d, bOm.d, bU.d, bE.d, bPhi.d
    assert dS + dE == dO and dU + dP == dE
    kO = fa(Fr(1, 2 * dO)).sqrt()                 # (2 d_Om)^(-1/2)
    kE4 = fa(2 * dE).sqrt().sqrt()               # (2 d_E)^(1/4)
    sq = (PI * dE).sqrt()
    # coef0, coef1: interpolation in the basis of Om
    pO = rand_points(rng, dO)
    S0, S1 = bS.values(pO), bS.values(pO, 1)
    E0, E1 = bE.values(pO), bE.values(pO, 1)
    cols0, colsH = [], []
    for s in range(dS):
        for g in range(dE):
            cols0.append([S0[s][p] * E0[g][p] for p in range(dO)])
            colsH.append([dS * E1[g][p] * S0[s][p] - dE * E0[g][p] * S1[s][p]
                          for p in range(dO)])
    C0, CH = interp(bOm, pO, cols0), interp(bOm, pO, colsH)
    coef0 = [[[C0[o, s * dE + g] * kO * kE4 for g in range(dE)]
              for o in range(dO)] for s in range(dS)]
    k1 = kO * kE4 / (sq * (dE + dS))
    coef1 = [[[CH[o, s * dE + g] * k1 for g in range(dE)]
              for o in range(dO)] for s in range(dS)]
    # P0, P0d, P1d: interpolation in the basis of E
    pE = rand_points(rng, dE)
    U0, U1 = bU.values(pE), bU.values(pE, 1)
    F0, F1 = bPhi.values(pE), bPhi.values(pE, 1)
    colsUF, colsH2 = [], []
    for u in range(dU):
        for w in range(dP):
            colsUF.append([U0[u][p] * F0[w][p] for p in range(dE)])
            colsH2.append([dP * U1[u][p] * F0[w][p] - dU * U0[u][p] * F1[w][p]
                           for p in range(dE)])
    CUF, CH2 = interp(bE, pE, colsUF), interp(bE, pE, colsH2)
    kE = 1 / kE4                                   # (2 d_E)^(-1/4)
    P0 = acb_mat(dE, dU * dP)
    P0d = acb_mat(dE, dU * dP)
    P1d = acb_mat(dE, dU * dP)
    for g in range(dE):
        for c in range(dU * dP):
            P0[g, c] = CUF[g, c] * kE
            P0d[g, c] = CH2[g, c] * kE / (dU + dP)
            P1d[g, c] = CUF[g, c] * kE * sq * dU / (dU + dP)
    A0 = acb_mat([[coef0[s][o][g] for g in range(dE)]
                  for s in range(dS) for o in range(dO)])
    A1 = acb_mat([[coef1[s][o][g] for g in range(dE)]
                  for s in range(dS) for o in range(dO)])
    out = {'Cup': A0 * P0, 'Dn': A1 * P0, 'F0': A0 * P0d, 'F1': A1 * P1d}
    shaped = {}
    for key, M in out.items():
        shaped[key] = [[[[M[s * dO + o, u * dP + w] for w in range(dP)]
                         for u in range(dU)] for o in range(dO)]
                       for s in range(dS)]
    return shaped, coef0, (pO, pE)


def q_tensor(bOm, bU, bQ, rng):
    """Q[o][u][m] = <U_u Q_m, F^Om_o>, the product into H^6(M3, M1)."""
    dO, dU, dQ = bOm.d, bU.d, bQ.d
    assert dU + dQ == dO
    kO = fa(Fr(1, 2 * dO)).sqrt()
    pO = rand_points(rng, dO)
    U0, Q0 = bU.values(pO), bQ.values(pO)
    cols = [[U0[u][p] * Q0[m][p] for p in range(dO)]
            for u in range(dU) for m in range(dQ)]
    C = interp(bOm, pO, cols)
    return [[[C[o, u * dQ + m] * kO for m in range(dQ)] for u in range(dU)]
            for o in range(dO)]


