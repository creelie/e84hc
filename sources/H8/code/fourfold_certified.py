from flint import acb, acb_mat, arb, ctx

ctx.prec = 128
PI = arb.pi()
PASS, FAIL = [], []


def check(name, ok, detail=""):
    (PASS if ok else FAIL).append(name)
    print(("  [PASS] " if ok else "  [FAIL] ") + name +
          (("   " + detail) if detail else ""))


def fa(q):
    """The exact ball of a rational number."""
    q = Fr(q)
    return arb(q.numerator) / q.denominator


def cis(q):
    """exp(2 pi i q) for rational q."""
    q = Fr(q) % 1
    return acb(fa(2 * q)).exp_pi_i()


def zeros(r, c):
    return acb_mat(r, c)


def mat(rows):
    return acb_mat([[x for x in row] for row in rows])


def kron(A, B):
    ra, ca, rb, cb = A.nrows(), A.ncols(), B.nrows(), B.ncols()
    out = acb_mat(ra * rb, ca * cb)
    for i in range(ra):
        for j in range(ca):
            a = A[i, j]
            for k in range(rb):
                for l in range(cb):
                    out[i * rb + k, j * cb + l] = a * B[k, l]
    return out


def ident(n):
    out = acb_mat(n, n)
    for i in range(n):
        out[i, i] = acb(1)
    return out


