"""Item (LXXII), part (H): the rank of the fourfold products, certified.

The rank of prop:fourfoldrank is computed here in ball arithmetic (Arb, through
python-flint, at 128 bits), so that every number carries a rigorous error
bound and the rank is proved, not estimated.  Nothing is computed by
quadrature and nothing in floating point.  The method rests on four exact
facts, each proved in the paper or recalled below.

  1. Theta functions.  On E_0 = C/Z[i] a line bundle of degree d > 0 with
     semicharacter exp(2 pi i r) has, in the symmetric unitary gauge, the
     basis F_k (k = 0, ..., d - 1) of item (LXXII), with |F_k|^2 integrating
     to (2d)^(-1/2), the F_k pairwise orthogonal, and nabla_z^l F_k of norm
     squared l! (pi d)^l (2d)^(-1/2).  The series converge with the explicit
     tail bound of `tail`, so every value is an exact ball.

  2. Levels of a product.  For holomorphic sections a, b of degrees d_a, d_b,
     nabla(a b) is of level one and H = d_b (nabla a) b - d_a a (nabla b) is
     holomorphic, since [nabla_zbar, nabla_z] = -pi d; so
     (nabla a) b = d_a/(d_a + d_b) nabla(a b) + H/(d_a + d_b).  Every integral
     of item (LXXII) is therefore an inner product of a holomorphic section
     with a theta function, that is a coefficient of a holomorphic section in
     the basis F_k, multiplied by (2d)^(-1/2).

  3. Coefficients by interpolation.  A holomorphic section of degree d is
     determined by its values at d points at which the matrix (F_k(z_p)) is
     invertible; Arb solves that system and returns balls that contain the
     exact coefficients.

  4. Descent.  The sections on B_j are the sections on the cover E_0 x E_0
     invariant under the kernel K of phi_zeta, generated by the half periods
     k_1 = (1/2, 1/2) and k_2 = (i/2, i/2).  Each acts by
     R f(w) = c^(-1) exp(-i pi Im H(w, k)) f(w + k), a tensor product of
     operators on the two curves, and R_1^2 = R_2^2 = 1, R_1 R_2 = R_2 R_1
     exactly (checked below in rational arithmetic), so
     P = (1 + R_1)(1 + R_2)/4 projects onto the invariant sections.  The
     theta basis of B_j pulls back to the cover by phi_zeta exactly (the
     symmetric gauge is invariant under the unitary map phi_zeta / sqrt 2),
     and its coefficients are found by interpolation, as in 3.

With these, the 729 x 192 matrix of prop:fourfoldrank is a matrix of balls,
and the determinant of its Gram matrix is a ball that does not contain 0, so
the rank is exactly 192 at the chosen data.  The data (semicharacters,
sample points, components) are exact rationals drawn with a fixed seed.

  (H) checks:
    - the group relations of K and the dimensions |det| of the invariant
      sections, exactly;
    - the level decomposition against the quadrature of item (LXXII) on one
      curve (to 1e-11);
    - rank 192 on the 192 classes of type (1,1,0) at p = 0, t = (2, 5, 6),
      and rank 12 on each of the sixteen pieces, certified;
    - the same with x1 x2^zeta = 0 = x2^zeta x3^zeta, certified, the kernels
      of dimensions 11 and 19 being certified as well;
    - the same with the relative sign of the two terms reversed, and at
      t = (2, 5, 7), certified.
"""
