# 1. theta functions on E_0 in the symmetric unitary gauge

MTERMS = 10


def tail(d, Y, level):
    """Upper bound for sum_{|m| > MTERMS} |P_level(xi)| exp(-pi d xi^2),
    where |xi| >= |m| - Y and |xi| <= |m| + Y, P_0 = 1, P_1 = 2 pi i d xi.
    With j = |m| - Y >= J0 = MTERMS + 1 - Y and q = exp(-pi d J0), one has
    exp(-pi d j^2) <= q^j, |P| <= A + B j with A = 1 + 2 pi d (2Y),
    B = 2 pi d, and each j occurs for at most two m."""
    J0 = MTERMS + 1 - Y
    assert J0 >= 1
    q = (-PI * d * J0).exp()
    s0 = q ** J0 / (1 - q)
    s1 = q ** J0 * (arb(J0) / (1 - q) + q / (1 - q) ** 2)
    A = 1 + (2 * PI * d * 2 * Y if level else 0)
    B = 2 * PI * d if level else 0
    bound = 2 * (A * s0 + B * s1)
    return float(bound.mid() + bound.rad()) * 2.0


class CBundle:
    """Degree d > 0, semicharacter exp(2 pi i r1) on 1 and exp(2 pi i ri) on
    i, with r1, ri rational.  F_k(z) = sum_m exp(-pi d xi^2 +
    2 pi i (d x y / 2 + n x - m ri)), s = k + alpha, alpha = r1 mod 1,
    n = s + m d, xi = y + m + s / d (the basis of item (LXXII))."""

    def __init__(self, d, r1, ri):
        assert d > 0
        self.d, self.r1, self.ri = d, Fr(r1) % 1, Fr(ri) % 1
        self.alpha = self.r1
        self.cache = {}

    def value(self, k, z, level=0):
        key = (k, z, level)
        if key in self.cache:
            return self.cache[key]
        x, y = z
        d = self.d
        s = k + self.alpha
        tot = acb(0)
        for m in range(-MTERMS, MTERMS + 1):
            n = s + m * d
            xi = y + m + s / d
            ph = Fr(d) * x * y / 2 + n * x - m * self.ri
            t = (-PI * d * fa(xi * xi)).exp() * cis(ph)
            if level == 1:
                t = t * acb(0, 2 * PI * d * fa(xi))
            tot += t
        Y = int(abs(y)) + 2
        r = tail(d, Y, level)
        tot += acb(arb(0, r), arb(0, r))
        self.cache[key] = tot
        return tot

    def values(self, pts, level=0):
        return [[self.value(k, z, level) for z in pts] for k in range(self.d)]

    def floats(self):
        import numpy as np
        return (np.exp(2j * np.pi * float(self.r1)),
                np.exp(2j * np.pi * float(self.ri)))


def rand_points(rng, n, lo=0, span=1):
    return [(Fr(rng.randrange(1, 2 ** 12), 2 ** 12) * span + lo,
             Fr(rng.randrange(1, 2 ** 12), 2 ** 12) * span + lo)
            for _ in range(n)]


def interp(bundle, pts, columns):
    """Coefficients in the basis F_k of the holomorphic sections whose values
    at the points pts (len(pts) = d) are the given columns."""
    d = bundle.d
    V = acb_mat([[bundle.value(k, z) for k in range(d)] for z in pts])
    R = acb_mat([[col[p] for col in columns] for p in range(d)])
    return V.solve(R)


