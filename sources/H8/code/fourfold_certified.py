# surfaces, pieces and covers, with exact rational semicharacters

BASIS = [(1, 0), (1j, 0), (0, 1), (0, 1j)]


def herm(x, y, H):
    return sum(x[a] * H[a][b] * complex(y[b]).conjugate()
               for a in range(2) for b in range(2))


class Piece:
    def __init__(self, H, vals):
        self.H = [[complex(H[a][b]) for b in range(2)] for a in range(2)]
        self.vals = [Fr(v) for v in vals]
        self.E = [[int(round(herm(BASIS[k], BASIS[l], self.H).imag))
                   for l in range(4)] for k in range(4)]

    def chi(self, n):
        q = sum(n[k] * n[l] * self.E[k][l] for k in range(4)
                for l in range(k + 1, 4))
        return (sum(n[k] * self.vals[k] for k in range(4)) + Fr(q, 2)) % 1


class Hom:
    def __init__(self, a, b):
        self.a, self.b = a, b
        self.H = [[b.H[i][j] - a.H[i][j] for j in range(2)] for i in range(2)]

    def chi(self, n):
        return (self.b.chi(n) - self.a.chi(n)) % 1

    def det(self):
        H = self.H
        return int(round((H[0][0] * H[1][1] - H[0][1] * H[1][0]).real))


class Cover:
    def __init__(self, zeta):
        self.zeta = complex(zeta)
        self.P = [[1, 1], [self.zeta, -self.zeta]]

    def phi(self, w):
        return (w[0] + w[1], self.zeta * w[0] - self.zeta * w[1])

    @staticmethod
    def nvec(x):
        return [int(round(x[0].real)), int(round(x[0].imag)),
                int(round(x[1].real)), int(round(x[1].imag))]

    def pullform(self, hom):
        P, H = self.P, hom.H
        return [[sum(P[a][i] * H[a][b] * complex(P[b][j]).conjugate()
                     for a in range(2) for b in range(2))
                 for j in range(2)] for i in range(2)]

    def bundles(self, hom):
        Hp = self.pullform(hom)
        assert abs(Hp[0][1]) < 1e-12
        out = []
        for col in (0, 1):
            d = int(round(Hp[col][col].real))
            e = [0, 0]
            e[col] = 1
            ie = [0, 0]
            ie[col] = 1j
            out.append(CBundle(d, hom.chi(self.nvec(self.phi(e))),
                               hom.chi(self.nvec(self.phi(ie)))))
        return out


def translation(b, k, rng):
    """Matrix of f -> exp(-i pi d Im(w conj k)) f(w + k) on the theta basis,
    for k = 1/2 or i/2, by interpolation."""
    pts = rand_points(rng, b.d)
    if k == '1/2':
        shift = [(x + Fr(1, 2), y) for x, y in pts]
        fac = [cis(-Fr(b.d) * y / 4) for x, y in pts]          # e^{-i pi d y/2}
    else:
        shift = [(x, y + Fr(1, 2)) for x, y in pts]
        fac = [cis(Fr(b.d) * x / 4) for x, y in pts]           # e^{i pi d x/2}
    cols = [[fac[p] * b.value(a, shift[p]) for p in range(b.d)]
            for a in range(b.d)]
    return interp(b, pts, cols)


def projector(cover, hom, Bu, Bv, rng):
    """The projector onto the K-invariant sections, with the exact check of
    the group relations: (R^u_{1/2})^2 = chi_1^u, (R^u_{i/2})^2 = chi_i^u,
    and R_{1/2} R_{i/2} = (-1)^{d/2} R_{i/2} R_{1/2} on a curve of degree d."""
    ck1 = hom.chi(cover.nvec(cover.phi((0.5, 0.5))))
    ck2 = hom.chi(cover.nvec(cover.phi((0.5j, 0.5j))))
    exact = ((-2 * ck1 + Bu.r1 + Bv.r1) % 1 == 0
             and (-2 * ck2 + Bu.ri + Bv.ri) % 1 == 0
             and Bu.d % 2 == 0 and Bv.d % 2 == 0
             and ((Bu.d + Bv.d) // 2) % 2 == 0)
    Ru1, Ru2 = translation(Bu, '1/2', rng), translation(Bu, 'i/2', rng)
    Rv1, Rv2 = translation(Bv, '1/2', rng), translation(Bv, 'i/2', rng)
    R1 = kron(Ru1, Rv1) * cis(-ck1)
    R2 = kron(Ru2, Rv2) * cis(-ck2)
    n = Bu.d * Bv.d
    I = ident(n)
    P = (I + R1) * (I + R2) * acb(fa(Fr(1, 4)))
    tr = sum((P[i, i] for i in range(n)), acb(0))
    det = abs(hom.det())
    balls = ((R1 * R1 - I).contains(acb_mat(n, n))
             and (R2 * R2 - I).contains(acb_mat(n, n))
             and (R1 * R2 - R2 * R1).contains(acb_mat(n, n)))
    dim_ok = tr.contains(det) and tr.rad() < 0.25
    return P, exact and balls, dim_ok


def zpull(cover, hom, d, Bu, Bv, rng):
    """Coefficients of the pulled-back theta basis of B (degree d in each
    coordinate) in the product basis of the cover, by interpolation."""
    assert hom.H[0][0] == hom.H[1][1] == d and hom.H[0][1] == 0
    B1 = CBundle(d, hom.chi([1, 0, 0, 0]), hom.chi([0, 1, 0, 0]))
    B2 = CBundle(d, hom.chi([0, 0, 1, 0]), hom.chi([0, 0, 0, 1]))
    n = Bu.d * Bv.d
    w1s, w2s = rand_points(rng, n), rand_points(rng, n)
    z = cover.zeta
    zr, zi = int(round(z.real)), int(round(z.imag))
    G = acb_mat(n, n)
    Z = acb_mat(n, d * d)
    for p in range(n):
        (x1, y1), (x2, y2) = w1s[p], w2s[p]
        for a in range(Bu.d):
            for b in range(Bv.d):
                G[p, a * Bv.d + b] = Bu.value(a, w1s[p]) * Bv.value(b, w2s[p])
        za = (x1 + x2, y1 + y2)
        dx, dy = x1 - x2, y1 - y2
        zb = (zr * dx - zi * dy, zr * dy + zi * dx)
        for i1 in range(d):
            for i2 in range(d):
                Z[p, i1 * d + i2] = B1.value(i1, za) * B2.value(i2, zb)
    return G.solve(Z)


