    # tau^4 = 17/64 + (7/8) sqrt(-2) acts on (a, b) by [[17/64, -7/8],
    # [7/4, 17/64]]: omega_1 -> 17/64 omega_1 + 7/4 omega_2
    al, be = 17 / 64, 7 / 8
    rho = math.hypot(al, be * math.sqrt(d))           # |tau^4| = Nm(tau)^2
    th = math.atan2(be * math.sqrt(d), al)             # arg tau^4

