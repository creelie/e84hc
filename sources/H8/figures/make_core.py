def fig_weilcube():
    """The sixteen monomials w^(T), T in {1,2,3,4}, as the vertices of the
    4-cube under the linear projection e_j -> (a_j, 1), so that the height of
    w^(T) is |T| and all edges of one direction j are parallel; each vertex is
    written as the monomial itself, in the colour of the class it lies in."""
    a = (-2.25, -0.25, 0.75, 1.75)       # the horizontal parts of e_1..e_4
    G, HH = 1.54, 1.12                   # pitch of the middle row, of the rows
    BW, BH = 1.34, 0.38                  # the extent of a monomial
    GAP = 0.07                           # between an edge and a monomial
    F = Fig("fig_weilcube",
            "The 2^{2n} = 16 monomials w^(T) at n = 2 as the vertices of the "
            "4-cube under the linear projection e_j -> (a_j, 1): the height is "
            "|T|, edges of one direction are parallel, and the parity of |T| "
            "separates omega_1 from omega_2.")

    def pos(T):
        return (G * sum(a[j] for j in range(4) if T >> j & 1),
                HH * bin(T).count("1"))

    def mono(T):
        return "".join(("y_{%d}" if T >> j & 1 else "x_{%d}") % (j + 1)
                       for j in range(4))

    def clip(p, q):
        """the part of the segment pq outside the two monomials, less GAP"""
        dx, dy = q[0] - p[0], q[1] - p[1]
        hx, hy = BW / 2 + GAP, BH / 2 + GAP
        t = min(hx / abs(dx) if dx else 9.0, hy / abs(dy))
        return ((p[0] + t * dx, p[1] + t * dy), (q[0] - t * dx, q[1] - t * dy))

    # the 32 edges
    for T in range(16):
        for j in range(4):
            if T >> j & 1:
                continue
            (x0, y0), (x1, y1) = clip(pos(T), pos(T | 1 << j))
            F.flat("  \\draw[PSlate!75,line width=0.45pt] (%s,%s) -- (%s,%s);\n"
                   % (f4(x0), f4(y0), f4(x1), f4(y1)), under=True)
    # the sixteen vertices, each the monomial w^(T)
    for T in range(16):
        x, y = pos(T)
        even = bin(T).count("1") % 2 == 0
        F.label(x, y, "$%s$" % mono(T), font=r"\footnotesize",
                color="PIndigo" if even else "PTeal",
                extra="text height=1.5ex,text depth=0.45ex")

    # the axis of |T| on the left
    xl = -G * 2.5 - BW / 2 - 0.30
    F.flat("  \\draw[PInk,line width=0.45pt] (%s,%s) -- (%s,%s);\n"
           % (f4(xl), f4(-0.12), f4(xl), f4(4 * HH + 0.12)))
    for k in range(5):
        F.flat("  \\draw[PInk,line width=0.45pt] (%s,%s) -- (%s,%s);\n"
               % (f4(xl - 0.10), f4(k * HH), f4(xl), f4(k * HH)))
        F.label(xl - 0.17, k * HH, "$%d$" % k, anchor="east",
                font=r"\footnotesize")
    F.label(xl, 4 * HH + 0.30, r"$\lvert T\rvert$", anchor="south")

    # on the right, for each level: the class and the common coefficient
    xr = G * 2.5 + BW / 2 + 0.38
    cols = (0.25, 1.58)
    who = [r"$\omega_{1}$", r"$\omega_{2}$"] * 2 + [r"$\omega_{1}$"]
    coef = [r"$d^{2}$", r"$d$", r"$-d$", r"$-1$", r"$1$"]
    for k in range(5):
        col = "PIndigo" if k % 2 == 0 else "PTeal"
        F.label(xr + cols[0], k * HH, who[k], color=col)
        F.label(xr + cols[1], k * HH, coef[k])
    ytop = 4 * HH + 0.62
    for c, t in zip(cols, ("class", "coefficient")):
        F.label(xr + c, ytop, t, font=r"\footnotesize",
                extra="text height=1.6ex,text depth=0.4ex")
    F.flat("  \\draw[PRule,line width=0.45pt] (%s,%s) -- (%s,%s);\n"
           % (f4(xr - 0.18), f4(ytop - 0.28), f4(xr + cols[1] + 0.74),
              f4(ytop - 0.28)))

    # the generating product, which gives every coefficient at once
    F.label(0.0, -0.88,
            r"$\omega_{1}+\delta\,\omega_{2}=d^{-2}\prod_{j=1}^{4}"
            r"\bigl(d\,x_{j}+\delta\,y_{j}\bigr)=\sum_{T}d^{\,2-\lvert T\rvert}"
            r"\,\delta^{\lvert T\rvert}\,w^{(T)},\qquad \delta^{2}=-d$",
            anchor="north")
    F.write(thr=222)


