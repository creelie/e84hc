# =============================================================== annihilator
def fig_annihilator():
    """H^{0,2} = wedge^2 H^{0,1} at n = 3 as the strict upper triangle of the
    6 x 6 array on the basis u_1, u_2, u_3 of V_+^{0,1} and v_1, v_2, v_3 of
    V_-^{0,1}: the fifteen products e_i ^ e_j, i < j, each in its cell, in
    the three blocks of lem:annihilator, and beside each block what
    z -> z.omega does to it."""
    n = 3
    N = 2 * n
    CW, CH = 1.28, 0.64                         # the cell
    basis = [r"u_{%d}" % (k + 1) for k in range(n)] + \
            [r"v_{%d}" % (k + 1) for k in range(n)]
    F = Fig("fig_annihilator",
            "H^{0,2} = wedge^2 H^{0,1} at n = 3 as the strict upper triangle "
            "of the 6 x 6 array: the two outer blocks are carried injectively "
            "by z -> z.omega, the n^2 = 9 mixed products form its kernel.")
    PLUS, MIX, MINUS = "PIndigo", "PClay", "PTeal"

    def X(j):
        return j * CW

    def Y(i):
        return -i * CH

    def block(i, j):
        if j < n:
            return PLUS
        if i >= n:
            return MINUS
        return MIX

    # the fifteen cells, each with its product
    for i in range(N):
        for j in range(i + 1, N):
            c = block(i, j)
            F.flat("  \\path[fill=%s!9,draw=%s!45,line width=0.3pt] (%s,%s) "
                   "rectangle (%s,%s);\n"
                   % (c, c, f4(X(j)), f4(Y(i)), f4(X(j + 1)), f4(Y(i + 1))),
                   under=True)
            F.label(X(j) + CW / 2, Y(i) - CH / 2,
                    r"$%s\wedge %s$" % (basis[i], basis[j]),
                    font=r"\footnotesize", color="%s!70!black" % c)
    # the three blocks, outlined
    outline = "line width=0.9pt,line join=miter"
    F.flat("  \\draw[%s,%s] (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- "
           "(%s,%s) -- (%s,%s) -- cycle;\n"
           % (PLUS, outline, f4(X(1)), f4(Y(0)), f4(X(3)), f4(Y(0)),
              f4(X(3)), f4(Y(2)), f4(X(2)), f4(Y(2)), f4(X(2)), f4(Y(1)),
              f4(X(1)), f4(Y(1))))
    F.flat("  \\draw[%s,%s] (%s,%s) rectangle (%s,%s);\n"
           % (MIX, outline, f4(X(3)), f4(Y(0)), f4(X(6)), f4(Y(3))))
    F.flat("  \\draw[%s,%s] (%s,%s) -- (%s,%s) -- (%s,%s) -- (%s,%s) -- "
           "(%s,%s) -- (%s,%s) -- cycle;\n"
           % (MINUS, outline, f4(X(4)), f4(Y(3)), f4(X(6)), f4(Y(3)),
              f4(X(6)), f4(Y(5)), f4(X(5)), f4(Y(5)), f4(X(5)), f4(Y(4)),
              f4(X(4)), f4(Y(4))))

    # the basis: the columns on top, the rows on the diagonal, where
    # e_k ^ e_k = 0; and the splitting H^{0,1} = V_+^{0,1} + V_-^{0,1} as
    # braces over the columns
    for k in range(N):
        c = PLUS if k < n else MINUS
        F.label(X(k) + CW / 2, Y(0) + 0.26, "$%s$" % basis[k], color=c)
        F.label(X(k) + CW - 0.16, Y(k) - CH / 2, "$%s$" % basis[k],
                anchor="east", color=c)
    for k0, c, t in ((0, PLUS, r"$V_{+}^{0,1}$"), (n, MINUS, r"$V_{-}^{0,1}$")):
        F.flat("  \\draw[%s,line width=0.5pt,decorate,decoration={brace,"
               "amplitude=4pt}] (%s,%s) -- (%s,%s);\n"
               % (c, f4(X(k0) + 0.08), f4(Y(0) + 0.56), f4(X(k0 + n) - 0.08),
                  f4(Y(0) + 0.56)))
        F.label(X(k0) + n * CW / 2, Y(0) + 1.04, t, color=c)

    # what z -> z.omega does to each block
    xr = X(N) + 0.40
    F.label(xr, Y(0) - 0.15,
            r"$V_{+}^{0,1}\otimes V_{-}^{0,1}$,\ \ $\dim n^{2}=9$",
            anchor="west", color="%s!85!black" % MIX)
    F.label(xr, Y(0) - 0.80, r"$u\wedge v\;\longmapsto\;u\wedge v\wedge\omega=0$",
            anchor="west", color="%s!85!black" % MIX)
    F.label(xr, Y(0) - 1.40,
            r"since $u\wedge\alpha_{+}=0$ and $v\wedge\alpha_{-}=0$",
            anchor="west", color="%s!85!black" % MIX, font=r"\footnotesize")
    F.label(xr, Y(3) - 0.35,
            r"$\bigwedge^{2}V_{-}^{0,1}$,\ \ $\dim\binom{n}{2}=3$",
            anchor="west", color="%s!85!black" % MINUS)
    F.label(xr, Y(3) - 1.00,
            r"$z\;\longmapsto\;a\,z\wedge\alpha_{+}$, injective",
            anchor="west", color="%s!85!black" % MINUS)
    xl, yl = X(0) - 0.10, Y(4) - 0.35
    F.label(xl, yl, r"$\bigwedge^{2}V_{+}^{0,1}$,\ \ $\dim\binom{n}{2}=3$",
            anchor="west", color="%s!85!black" % PLUS)
    F.label(xl, yl - 0.65,
            r"$z\;\longmapsto\;b\,z\wedge\alpha_{-}$, injective",
            anchor="west", color="%s!85!black" % PLUS)
    F.leader((X(1) + 0.22, yl + 0.26), (X(1) + 0.22, Y(1) - 0.02), free=0.02,
             dot=False, style="%s!70,line width=0.45pt" % PLUS)

    # the Weil class, and the count
    F.label(X(0) - 0.10, Y(N) - 0.62,
            r"$\omega=a\,\alpha_{+}+b\,\alpha_{-}\in\HW(A)\otimes\RR$,\ \ "
            r"$ab\neq0$,\ \ $\alpha_{\pm}$ spanning $\bigwedge^{2n}V_{\pm}$",
            anchor="west")
    F.label(X(0) - 0.10, Y(N) - 1.27,
            r"$H^{0,2}(A)=\bigwedge^{2}H^{0,1}$,\ \ "
            r"$\dim\binom{2n}{2}=15=3+9+3$",
            anchor="west")
    F.write(thr=215)


# =================================================================== witness
def fig_witness():
    """c(tau)^n = (tau / conj tau)^n for n = 0..12 as helices on the cylinder
    S^1 x [0,12], for K = Q(sqrt-1) and K = Q(sqrt-3); the characters
    tau^{2n} and Nm(tau)^n agree at tau exactly on the seam c^n = 1."""
    cam = orbit_cam((0.0, 0.0, 1.85), 0, 4, R=60)
    F = Fig("fig_witness",
            "The values c(tau)^n = (tau/conj tau)^n, n = 0..12, as helices on "
            "a cylinder, for bad and good witnesses at d = 1 and d = 3; the "
            "characters agree at tau exactly where a helix meets the seam.",
            cam)
    R, HN, NMAX = 1.0, 0.31, 12
    ZT = HN * NMAX
    panels = [
        (-2.45, 1, [(1, "PClay"), (2, "PTeal")], (0, 4, 8, 12)),
        (2.45, 3, [(1, "PClay"), (3, "PAmber"), (2, "PTeal")], (0, 3, 6, 9, 12)),
    ]
    pts = []
    for cx, _, _, _ in panels:
        for t in range(0, 360, 10):
            a = math.radians(t)
            pts += [(cx + R * math.sin(a), -R * math.cos(a), 0),
                    (cx + R * math.sin(a), -R * math.cos(a), ZT)]
    fit(cam, pts, 9.4)

    def on(cx, th, z):
        return (cx + R * math.sin(th), -R * math.cos(th), z)

    def front(cx, th, z):
        p = on(cx, th, z)
        nrm = (math.sin(th), -math.cos(th), 0.0)
        return dot(nrm, sub(cam.eye, p)) > 0

    for cx, d, taus, marks in panels:
        # the cylinder: its front strips, translucent, over the back of the
        # helices; the rims at n = 0 and n = 12
        NS = 72
        for k in range(NS):
            a0, a1 = 2 * math.pi * k / NS, 2 * math.pi * (k + 1) / NS
            if not front(cx, 0.5 * (a0 + a1), 0.5 * ZT):
                continue
            quad = [on(cx, a0, 0), on(cx, a1, 0), on(cx, a1, ZT), on(cx, a0, ZT)]
            F.poly3(quad, fill=F.tone((math.sin(0.5 * (a0 + a1)),
                                       -math.cos(0.5 * (a0 + a1)), 0),
                                      "PSlate", lo=4, hi=14),
                    opacity=0.70, prio=-1, depth=1e5)
        for z in (0.0, ZT):
            ring = [on(cx, 2 * math.pi * k / 120, z) for k in range(121)]
            runs, cur, prev = [], [], None
            for k, p in enumerate(ring):
                f = front(cx, 2 * math.pi * k / 120, z)
                if prev is not None and f != prev:
                    runs.append((prev, cur))
                    cur = [cur[-1]]
                cur.append(p)
                prev = f
            runs.append((prev, cur))
            for f, run in runs:
                if len(run) > 1:
                    F.line3(run, "PSlate!70,line width=0.5pt" if f else
                            "PSlate!45,line width=0.4pt,dash pattern=on 1.5pt "
                            "off 1.3pt", prio=0 if f else -2,
                            depth=-1e5 if f else 2e5)
        # the two silhouettes and the seam c^n = 1
        for sx in (-1, 1):
            F.line3([(cx + sx * R, 0, 0), (cx + sx * R, 0, ZT)],
                     "PSlate!70,line width=0.5pt", prio=0, depth=-1e5)
        F.line3([on(cx, 0, 0), on(cx, 0, ZT)], "PInk,line width=0.75pt",
                prio=1, depth=-2e5)
        for n in range(NMAX + 1):
            F.line3([on(cx, -0.05, n * HN), on(cx, 0.05, n * HN)],
                    "PInk,line width=0.45pt", prio=1, depth=-2e5)
        # the helices, their back halves first
        for m, col in taus:
            tau = complex(m, math.sqrt(d))
            phi = math.atan2((tau / tau.conjugate()).imag,
                             (tau / tau.conjugate()).real)
            N = 600
            samp = [(k * NMAX / N) for k in range(N + 1)]
            cur, prev = [], None
            for t in samp:
                th = t * phi
                f = front(cx, th, t * HN)
                p = on(cx, th, t * HN)
                if prev is not None and f != prev:
                    cur.append(p)
                    F.line3(cur, "%s,line width=1.0pt" % col if prev else
                            "%s!40,line width=0.6pt" % col,
                            prio=2 if prev else -3,
                            depth=-3e5 if prev else 3e5)
                    cur = []
                cur.append(p)
                prev = f
            F.line3(cur, "%s,line width=1.0pt" % col if prev else
                    "%s!40,line width=0.6pt" % col, prio=2 if prev else -3,
                    depth=-3e5 if prev else 3e5)
            for n in range(NMAX + 1):
                th = n * phi
                f = front(cx, th, n * HN)
                F.dot3(on(cx, th, n * HN), col if f else "%s!40" % col,
                       r=1.55, prio=4 if f else -2,
                       depth=(-4e5 if f else 2.5e5))
        # the points where the characters agree, ringed
        for n in range(1, NMAX + 1):
            for m, col in taus:
                tau = complex(m, math.sqrt(d))
                c = tau / tau.conjugate()
                if abs(c ** n - 1) < 1e-9:
                    x, y = F.P(on(cx, 0, n * HN))
                    F.add(-5e5, "  \\draw[PInk,line width=0.6pt] (%s,%s) "
                                "circle (3.3pt);\n" % (f4(x), f4(y)), 5)
                    break
        # the scale of n on the left silhouette
        for n in marks:
            F.tick((cx - R, 0, n * HN), (cx - R - 0.14, 0, n * HN), "$%d$" % n,
                   font=r"\footnotesize")
        q = F.P((cx - R - 0.14, 0, ZT))
        F.label(q[0] - 0.02, q[1] + 0.30, "$n$", anchor="south east")
        # the field, and under it the witnesses
        q = F.P(on(cx, 0, 0))
        F.label(q[0], q[1] - 0.22, r"$K=\QQ(\sqrt{-%d})$" % d, anchor="north")
        y0 = q[1] - 0.95
        for k, (m, col) in enumerate(taus):
            yy = y0 - 0.46 * k
            xx = q[0] - 1.05
            F.flat("  \\draw[%s,line width=1.0pt] (%s,%s) -- (%s,%s);\n"
                   % (col, f4(xx - 0.30), f4(yy), f4(xx + 0.10), f4(yy)))
            F.flat("  \\fill[%s,draw=white,line width=0.45pt] (%s,%s) circle "
                   "(1.55pt);\n" % (col, f4(xx - 0.10), f4(yy)))
            F.label(xx + 0.22, yy, r"$\tau=%d+\sqrt{-%d}$" % (m, d),
                    anchor="west", color=col)
        # the seam
        q = F.P(on(cx, 0, ZT))
        F.label(q[0], q[1] + 0.20, r"$c(\tau)^{n}=1$", anchor="south")
    F.write()


