TIPS = "-{Stealth[length=4.2pt,width=3.2pt]}"


def binom(n, k):
    if k < 0 or k > n:
        return 0
    r = 1
    for i in range(k):
        r = r * (n - i) // (i + 1)
    return r


def f4(v):
    return "%.4f" % v


# ====================================================================== Fig
class Fig:
    """A figure: 3D items sorted by depth, flat ink, leaders and labels."""

    def __init__(self, name, blurb, cam=None, gen="make_core.py",
                 light=(0.45, -0.70, 0.85)):
        self.name, self.blurb, self.gen, self.cam = name, blurb, gen, cam
        self.light = unit(light)
        self.items = []          # (depth, priority, tikz)
        self.pre = []            # flat ink under the 3D items
        self.post = []           # flat ink over the 3D items
        self.labels = []         # dict(x, y, anchor, text, style)
        self.leaders = []        # dict(a, b, free, style, dot)

    # ---------------------------------------------------------- projection
    def P(self, p):
        return self.cam.project(p)[0]

    def D(self, p):
        return self.cam.project(p)[1]

    def path(self, pts):
        return " -- ".join("(%s,%s)" % (f4(q[0]), f4(q[1]))
                           for q in (self.P(p) for p in pts))

    def add(self, depth, tikz, prio=0):
        self.items.append((depth, prio, tikz))

    # ------------------------------------------------------------- shading
    def tone(self, nrm, base, lo=22, hi=78, amb=0.30, dif=0.70):
        """Lambert shading of a face with outward normal nrm, as a tint of
        base: lo per cent for a face turned to the light, hi for one turned
        away."""
        lam = max(0.0, dot(unit(nrm), self.light))
        inten = amb + dif * lam
        pct = hi - (hi - lo) * inten
        return "%s!%d!white" % (base, int(round(max(8, min(95, pct)))))

    def facing(self, centre, nrm):
        return dot(nrm, sub(self.cam.eye, centre)) > 0

    # --------------------------------------------------------------- solids
    def prism_tikz(self, lo, hi, base, edge=None, lw=0.32, opacity=None,
                   tones=None):
        """The visible faces of the box [lo, hi], shaded, as TikZ."""
        x0, y0, z0 = lo
        x1, y1, z1 = hi
        faces = [
            ((0, 0, -1), [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)]),
            ((0, 0, 1), [(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]),
            ((0, -1, 0), [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)]),
            ((0, 1, 0), [(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)]),
            ((-1, 0, 0), [(x0, y0, z0), (x0, y1, z0), (x0, y1, z1), (x0, y0, z1)]),
            ((1, 0, 0), [(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)]),
        ]
        out = []
        edge = edge or "%s!65!black" % base
        op = ("fill opacity=%.2f," % opacity) if opacity else ""
        for nrm, pts in faces:
            c = smul(0.25, (sum(p[0] for p in pts), sum(p[1] for p in pts),
                            sum(p[2] for p in pts)))
            if not self.facing(c, nrm):
                continue
            fill = (tones or {}).get(nrm) or self.tone(nrm, base)
            out.append("  \\path[%sfill=%s,draw=%s,line width=%.2fpt] %s -- cycle;\n"
                       % (op, fill, edge, lw, self.path(pts)))
        return "".join(out)

    def prism(self, lo, hi, base, prio=0, **kw):
        c = smul(0.5, addv(lo, hi))
        self.add(self.D(c), self.prism_tikz(lo, hi, base, **kw), prio)

    def stack(self, x0, y0, dx, dy, segs, prio=0, **kw):
        """A column of boxes [z_a, z_b] with colours, drawn bottom up as one
        item, so that the painter keeps them in order."""
        out = []
        for za, zb, base in segs:
            out.append(self.prism_tikz((x0, y0, za), (x0 + dx, y0 + dy, zb),
                                       base, **kw))
        c = (x0 + dx / 2, y0 + dy / 2, 0.5 * (segs[0][0] + segs[-1][1]))
        self.add(self.D(c), "".join(out), prio)

    def poly3(self, pts, fill=None, draw=None, lw=0.3, opacity=None,
              prio=0, depth=None, extra=""):
        opts = []
        if opacity is not None:
            opts.append("fill opacity=%.2f" % opacity)
        opts.append("fill=%s" % fill if fill else "fill=none")
        opts.append("draw=%s" % draw if draw else "draw=none")
        opts.append("line width=%.2fpt" % lw)
        if extra:
            opts.append(extra)
        d = depth if depth is not None else sum(self.D(p) for p in pts) / len(pts)
        self.add(d, "  \\path[%s] %s -- cycle;\n" % (",".join(opts),
                                                    self.path(pts)), prio)

    def line3(self, pts, style, prio=1, depth=None):
        d = depth if depth is not None else sum(self.D(p) for p in pts) / len(pts)
        self.add(d, "  \\draw[%s] %s;\n" % (style, self.path(pts)), prio)

    def curve3(self, pts, style, prio=1, chunk=6, depth=None):
        """A sampled curve, cut into short depth-sorted runs."""
        k = 0
        while k < len(pts) - 1:
            m = min(k + chunk, len(pts) - 1)
            seg = pts[k:m + 1]
            self.line3(seg, style, prio, depth)
            k = m

    def dot3(self, p, fill, r=1.6, ring="white", prio=3, depth=None):
        x, y = self.P(p)
        d = depth if depth is not None else self.D(p)
        self.add(d, "  \\fill[%s,draw=%s,line width=0.45pt] (%s,%s) circle "
                    "(%.2fpt);\n" % (fill, ring, f4(x), f4(y), r), prio)

    # ------------------------------------------------------------ flat ink
    def flat(self, tikz, under=False):
        (self.pre if under else self.post).append(tikz)

    # --------------------------------------------------------------- labels
    def label(self, x, y, text, anchor="center", color="PInk", font=None,
              extra=""):
        self.labels.append(dict(x=x, y=y, text=text, anchor=anchor,
                                color=color, font=font, extra=extra))
        return len(self.labels) - 1

    def label3(self, p, text, dx=0.0, dy=0.0, **kw):
        x, y = self.P(p)
        return self.label(x + dx, y + dy, text, **kw)

    def tick(self, p, q, text, gap=0.10, **kw):
        """A tick from p to q (3D) with its label beyond q, in the screen
        direction of the tick, anchored on the side facing the tick."""
        a, b = self.P(p), self.P(q)
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = math.hypot(dx, dy)
        dx, dy = dx / L, dy / L
        ang = math.degrees(math.atan2(dy, dx)) % 360
        names = ["west", "south west", "south", "south east", "east",
                 "north east", "north", "north west"]
        anchor = names[int(((ang + 22.5) % 360) // 45)]
        self.line3([p, q], "PInk,line width=0.35pt", prio=5, depth=-1)
        return self.label(b[0] + gap * dx, b[1] + gap * dy, text,
                          anchor=anchor, **kw)

    def edge_ticks(self, p0, p1, ts, texts, out, length=0.12, gap=0.06,
                   font=r"\footnotesize", color="PInk"):
        """Ticks on the 3D segment p0 p1 at the parameters ts, drawn in the
        screen direction perpendicular to the projected segment on the side
        of the screen point `out`, with their labels beyond them."""
        a, b = self.P(p0), self.P(p1)
        ex, ey = b[0] - a[0], b[1] - a[1]
        L = math.hypot(ex, ey)
        nx, ny = -ey / L, ex / L
        if (out[0] - a[0]) * nx + (out[1] - a[1]) * ny < 0:
            nx, ny = -nx, -ny
        ang = math.degrees(math.atan2(ny, nx)) % 360
        names = ["west", "south west", "south", "south east", "east",
                 "north east", "north", "north west"]
        anchor = names[int(((ang + 22.5) % 360) // 45)]
        for t, text in zip(ts, texts):
            p = tuple(p0[i] + t * (p1[i] - p0[i]) for i in range(3))
            x, y = self.P(p)
            self.flat("  \\draw[PInk,line width=0.35pt] (%s,%s) -- (%s,%s);\n"
                      % (f4(x), f4(y), f4(x + length * nx), f4(y + length * ny)))
            self.label(x + (length + gap) * nx, y + (length + gap) * ny, text,
                       anchor=anchor, font=font, color=color)
        return nx, ny

    def swatch(self, x, y, base, text, size=0.24, color="PInk", gap=0.14,
               font=None):
        """A legend entry: a shaded square at (x,y) and its text."""
        h = size / 2
        self.flat("  \\path[fill=%s!38!white,draw=%s!65!black,line width=0.32pt]"
                  " (%s,%s) rectangle (%s,%s);\n"
                  % (base, base, f4(x - h), f4(y - h), f4(x + h), f4(y + h)))
        return self.label(x + h + gap, y, text, anchor="west", color=color,
                          font=font, extra="text height=1.6ex,text depth=0.3ex")

    def leader(self, a, b, free=0.10, dot=True, style=LEADER):
        """A leader from a (next to its label) to b (on the object); only the
        last `free` cm of it may touch ink."""
        self.leaders.append(dict(a=a, b=b, free=free, dot=dot, style=style))

    SIMPLE = {"north west": ("west", -0.5), "south west": ("west", 0.5),
              "north east": ("east", -0.5), "south east": ("east", 0.5)}

    def _simple(self, x, y, an, h):
        """The same box with a simple anchor: checkfigs reads a compound
        anchor as centred, so the output never uses one."""
        if an in self.SIMPLE:
            a2, f = self.SIMPLE[an]
            return x, y + f * h, a2
        return x, y, an

    def _cfbox(self, L, x=None, y=None, an=None):
        import checkfigs
        M = dict(L)
        if x is not None:
            M["x"], M["y"], M["anchor"] = x, y, an
        spec = self._label_tex(M)
        m = re.match(r"\s*\\node\[([^\]]*)\]", spec)
        return checkfigs.box(m.group(1), M["x"], M["y"], M["text"])

    @staticmethod
    def _cf_hit(a, b):
        return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]

    def _label_tex(self, L, audit_name=None):
        opts = ["lbl"]
        if L["anchor"] != "center":
            opts.append("anchor=%s" % L["anchor"])
        opts.append("text=%s" % L["color"])
        if L["font"]:
            opts.append("font=%s" % L["font"])
        if L["extra"]:
            opts.append(L["extra"])
        if audit_name:
            opts += ["name=%s" % audit_name, "opacity=0"]
        return "  \\node[%s] at (%s,%s) {%s};\n" % (
            ",".join(opts), f4(L["x"]), f4(L["y"]), L["text"])

    def _leader_tex(self, Q):
        (ax, ay), (bx, by) = Q["a"], Q["b"]
        s = "  \\draw[%s] (%s,%s) -- (%s,%s);\n" % (Q["style"], f4(ax), f4(ay),
                                                   f4(bx), f4(by))
        if Q["dot"]:
            s += "  \\fill[PSlate] (%s,%s) circle (0.75pt);\n" % (f4(bx), f4(by))
        return s

    def body(self):
        items = sorted(self.items, key=lambda it: (-it[0], it[1]))
        return ("".join(self.pre) + "".join(it[2] for it in items)
                + "".join(self.post))

    def tex(self):
        return (HEAD.format(name=self.name, gen=self.gen, blurb=self.blurb)
                + self.body()
                + "".join(self._leader_tex(Q) for Q in self.leaders)
                + "".join(self._label_tex(L) for L in self.labels) + TAIL)

    # ---------------------------------------------------------------- audit
    def _render(self, dpi=400):
        """Compile the ink with every label as an invisible probe; return the
        raster of the ink, the exact label boxes (pt) and the maps from pt
        to pixels."""
        wd = tempfile.mkdtemp(prefix="audit_")
        names = ["L%d" % i for i in range(len(self.labels))]
        probe = "".join(
            "\\pgfpointanchor{%s}{south west}\\pgfgetlastxy\\ax\\ay"
            "\\pgfpointanchor{%s}{north east}\\pgfgetlastxy\\bx\\by"
            "\\typeout{AUDIT %s \\ax\\space\\ay\\space\\bx\\space\\by}"
            % (n, n, n) for n in names + ["current bounding box"])
        src = (HEAD.format(name=self.name, gen=self.gen, blurb="audit")
               + self.body()
               + "".join(self._label_tex(L, n) for L, n in zip(self.labels, names))
               + "\\pgfextra{%s}\n" % probe + TAIL)
        with open(os.path.join(wd, "a.tex"), "w") as f:
            f.write(src)
        env = dict(os.environ, TEXINPUTS=HERE + "//:" + os.environ.get("TEXINPUTS", ""))
        r = subprocess.run(["pdflatex", "-interaction=nonstopmode",
                            "-halt-on-error", "a.tex"], cwd=wd, env=env,
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit("audit compile failed for %s:\n%s"
                             % (self.name, r.stdout[-3000:]))
        boxes = {}
        for line in open(os.path.join(wd, "a.log"), errors="replace"):
            m = re.match(r"AUDIT (.+?) (-?[\d.]+)pt (-?[\d.]+)pt (-?[\d.]+)pt "
                         r"(-?[\d.]+)pt", line)
            if m:
                boxes[m.group(1)] = tuple(float(m.group(k)) for k in range(2, 6))
        subprocess.run(["pdftoppm", "-gray", "-r", str(dpi), "-singlefile",
                        "a.pdf", "a"], cwd=wd, check=True)
        img = read_pgm(os.path.join(wd, "a.pgm"))
        shutil.rmtree(wd, ignore_errors=True)
        bx0, by0, bx1, by1 = boxes["current bounding box"]
        sc = dpi / 72.27

        def px(X):
            return (X - bx0 + BORDER) * sc

        def py(Y):
            return (by1 + BORDER - Y) * sc
        return img, [boxes[n] for n in names], px, py

    @staticmethod
    def _dark(img, px, py, box, pad, thr):
        H, W = img.shape
        ax, ay, bx, by = box
        c0, c1 = int(math.floor(px(ax - pad))), int(math.ceil(px(bx + pad)))
        r0, r1 = int(math.floor(py(by + pad))), int(math.ceil(py(ay - pad)))
        r0, r1 = max(0, min(H, r0)), max(0, min(H, r1))
        c0, c1 = max(0, min(W, c0)), max(0, min(W, c1))
        if r1 <= r0 or c1 <= c0:
            return 0
        return int((img[r0:r1, c0:c1] < thr).sum())

    @staticmethod
    def _leader_hits(img, px, py, A, B, free, lthr):
        H, W = img.shape
        L = math.hypot(B[0] - A[0], B[1] - A[1])
        n = max(2, int(L / 0.25))
        hits = 0
        for k in range(n + 1):
            t = k / n
            if t * L < 0.8 or (1 - t) * L < free * PT:
                continue
            X = A[0] + t * (B[0] - A[0])
            Y = A[1] + t * (B[1] - A[1])
            cc, rr = int(round(px(X))), int(round(py(Y)))
            if 0 <= rr < H and 0 <= cc < W:
                win = img[max(0, rr - 1):rr + 2, max(0, cc - 1):cc + 2]
                if (win < lthr).any():
                    hits += 1
        return hits

    def alabel(self, target, text, color="PInk", font=None, prefer=45,
               spread=180, rmin=0.08, rmax=1.6, lead=0.34, free=0.13):
        """A label placed automatically near the screen point `target`: the
        nearest position, in the preferred direction first, whose box is clear
        of ink and of the other labels; beyond `lead` cm it gets a leader."""
        i = self.label(target[0], target[1], text, color=color, font=font)
        self.labels[i]["auto"] = dict(target=target, prefer=prefer,
                                      spread=spread, rmin=rmin, rmax=rmax,
                                      lead=lead, free=free)
        return i

    def _autoplace(self, dpi=400, thr=246, lthr=172, pad=1.1, gap=1.2):
        img, boxes, px, py = self._render(dpi)
        auto = [i for i, L in enumerate(self.labels) if "auto" in L]
        placed = {i: boxes[i] for i in range(len(boxes)) if i not in auto}
        cfp = []
        for i in placed:
            L = self.labels[i]
            x, y, an = self._simple(L["x"] * PT, L["y"] * PT, L["anchor"],
                                    boxes[i][3] - boxes[i][1])
            cfp.append(self._cfbox(L, x / PT, y / PT, an))
        segs = [((Q["a"][0] * PT, Q["a"][1] * PT), (Q["b"][0] * PT, Q["b"][1] * PT))
                for Q in self.leaders]
        names = ["west", "south west", "south", "south east", "east",
                 "north east", "north", "north west"]
        for i in auto:
            L = self.labels[i]
            A = L["auto"]
            bx = boxes[i]
            w, h = bx[2] - bx[0], bx[3] - bx[1]
            tx, ty = A["target"][0] * PT, A["target"][1] * PT
            angs = [A["prefer"] + d for d in
                    sorted({s * 15 * k for k in range(13) for s in (1, -1)
                            if 15 * k <= A["spread"]}, key=abs)]
            found = None
            r = A["rmin"]
            while r <= A["rmax"] + 1e-9 and found is None:
                for ang in angs:
                    ca, sa = math.cos(math.radians(ang)), math.sin(math.radians(ang))
                    x, y = tx + r * PT * ca, ty + r * PT * sa
                    an = names[int(((ang % 360) + 22.5) % 360 // 45)]
                    ox = {"west": 0, "east": -w, "south": -w / 2, "north": -w / 2,
                          "south west": 0, "north west": 0, "south east": -w,
                          "north east": -w}[an]
                    oy = {"south": 0, "north": -h, "west": -h / 2, "east": -h / 2,
                          "south west": 0, "south east": 0, "north west": -h,
                          "north east": -h}[an]
                    box = (x + ox, y + oy, x + ox + w, y + oy + h)
                    if self._dark(img, px, py, box, pad, thr):
                        continue
                    sx, sy, sa = self._simple(x, y, an, h)
                    cfb = self._cfbox(L, sx / PT, sy / PT, sa)
                    if any(self._cf_hit(cfb, c) for c in cfp):
                        continue
                    if any(box[0] - gap < b[2] and b[0] - gap < box[2]
                           and box[1] - gap < b[3] and b[1] - gap < box[3]
                           for b in placed.values()):
                        continue
                    if any(seg_box(S[0], S[1], (box[0] - pad, box[1] - pad,
                                                box[2] + pad, box[3] + pad))
                           for S in segs):
                        continue
                    leader = None
                    if r > A["lead"]:
                        leader = ((x, y), (tx, ty))
                        if self._leader_hits(img, px, py, leader[0], leader[1],
                                             A["free"], lthr):
                            continue
                        if any(seg_box(leader[0], leader[1],
                                       (b[0] - pad, b[1] - pad, b[2] + pad,
                                        b[3] + pad))
                               for b in placed.values()):
                            continue
                        if any(seg_seg(leader, S) for S in segs):
                            continue
                    found = (x, y, an, box, leader, cfb)
                    break
                r += 0.025
            if found is None:
                if os.environ.get("FIGDRAFT") is None:
                    raise SystemExit("no place for label %r in %s"
                                     % (L["text"], self.name))
                print("    no place for", L["text"])
                del L["auto"]
                continue
            x, y, an, box, leader, cfb = found
            L["x"], L["y"], L["anchor"] = x / PT, y / PT, an
            placed[i] = box
            cfp.append(cfb)
            if leader:
                self.leader((x / PT, y / PT), A["target"], free=A["free"])
                segs.append(leader)
            del L["auto"]

    def audit(self, dpi=400, thr=246, lthr=172, pad=1.1, gap=1.2):
        """Rasterise the ink without labels and leaders, read the exact label
        boxes from TeX, and return the list of collisions."""
        img, lab, px, py = self._render(dpi)
        bad = []
        # ink under a label
        for i, box in enumerate(lab):
            k = self._dark(img, px, py, box, pad, thr)
            if k:
                bad.append("ink under label %r (%d px)" % (self.labels[i]["text"], k))
        # label against label
        for i in range(len(lab)):
            for j in range(i + 1, len(lab)):
                a, b = lab[i], lab[j]
                if (a[0] - gap < b[2] and b[0] - gap < a[2]
                        and a[1] - gap < b[3] and b[1] - gap < a[3]):
                    bad.append("labels touch: %r / %r" % (self.labels[i]["text"],
                                                          self.labels[j]["text"]))
        # the estimate of checkfigs.py must pass as well
        cfs = [self._cfbox(L) for L in self.labels]
        for i in range(len(cfs)):
            for j in range(i + 1, len(cfs)):
                if self._cf_hit(cfs[i], cfs[j]):
                    bad.append("checkfigs estimate: %r / %r"
                               % (self.labels[i]["text"], self.labels[j]["text"]))
        # leaders: clear of ink but for their last `free` cm, of the labels
        # but their own, and of each other
        segs = []
        for Q in self.leaders:
            A = (Q["a"][0] * PT, Q["a"][1] * PT)
            B = (Q["b"][0] * PT, Q["b"][1] * PT)
            segs.append((A, B))
            hits = self._leader_hits(img, px, py, A, B, Q["free"], lthr)
            if hits:
                bad.append("leader to %r crosses ink (%d samples)"
                           % (Q["b"], hits))
            for i, (ax, ay, bx, by) in enumerate(lab):
                if seg_box(A, B, (ax - pad, ay - pad, bx + pad, by + pad),
                           skip_end=A):
                    bad.append("leader to %r crosses label %r"
                               % (Q["b"], self.labels[i]["text"]))
        for i in range(len(segs)):
            for j in range(i + 1, len(segs)):
                if seg_seg(segs[i], segs[j]):
                    bad.append("leaders cross: %r / %r" % (self.leaders[i]["b"],
                                                           self.leaders[j]["b"]))
        return bad

    # ---------------------------------------------------------------- write
    def write(self, strict=None, **kw):
        if strict is None:
            strict = os.environ.get("FIGDRAFT") is None
        if any("auto" in L for L in self.labels):
            self._autoplace(**kw)
        if any(L["anchor"] in self.SIMPLE for L in self.labels):
            _, boxes, _, _ = self._render()
            for L, b in zip(self.labels, boxes):
                x, y, an = self._simple(L["x"], L["y"], L["anchor"],
                                        (b[3] - b[1]) / PT)
                L["x"], L["y"], L["anchor"] = x, y, an
        bad = self.audit(**kw)
        for b in bad:
            print("   ", self.name, ":", b)
        if bad and strict:
            raise SystemExit("audit failed for %s" % self.name)
        with open(os.path.join(HERE, self.name + ".tex"), "w") as f:
            f.write(self.tex())
        print("%-18s %2d labels, %2d leaders, audited clear"
              % (self.name, len(self.labels), len(self.leaders)))
        compile_figure(self.name)


def compile_figure(name):
    """pdflatex in the figures folder, a check of the log for missing glyphs,
    the 200 dpi PNG, and the cleanup."""
    r = subprocess.run(["pdflatex", "-interaction=nonstopmode",
                        "-halt-on-error", name + ".tex"], cwd=HERE,
                       capture_output=True, text=True)
    log = os.path.join(HERE, name + ".log")
    text = open(log, errors="replace").read() if os.path.exists(log) else ""
    if r.returncode != 0:
        sys.stdout.write(r.stdout[-3000:])
        raise SystemExit("pdflatex failed on %s" % name)
    for bad in ("Missing character", "Overfull", "Undefined control"):
        if bad in text:
            raise SystemExit("%s: '%s' in the log" % (name, bad))
    subprocess.run(["pdftoppm", "-png", "-r", "200", "-singlefile",
                    name + ".pdf", name], cwd=HERE, check=True)
    for ext in (".aux", ".log"):
        try:
            os.remove(os.path.join(HERE, name + ext))
        except OSError:
            pass


def read_pgm(path):
    data = open(path, "rb").read()
    tok, i = [], 0
    while len(tok) < 4:
        while data[i:i + 1].isspace():
            i += 1
        if data[i:i + 1] == b"#":
            while data[i:i + 1] not in (b"\n", b""):
                i += 1
            continue
        j = i
        while not data[j:j + 1].isspace():
            j += 1
        tok.append(data[i:j])
        i = j
    i += 1
    w, h = int(tok[1]), int(tok[2])
    return np.frombuffer(data, dtype=np.uint8, count=w * h,
                         offset=i).reshape(h, w)


def seg_box(A, B, box, skip_end=None):
    """Does the segment AB meet the box (x0,y0,x1,y1)?  The part within
    1.5pt of skip_end is ignored, since a leader starts at its own label."""
    x0, y0, x1, y1 = box
    L = math.hypot(B[0] - A[0], B[1] - A[1])
    n = max(2, int(L / 0.3))
    for k in range(n + 1):
        t = k / n
        X = A[0] + t * (B[0] - A[0])
        Y = A[1] + t * (B[1] - A[1])
        if skip_end is not None and math.hypot(X - skip_end[0],
                                               Y - skip_end[1]) < 1.5:
            continue
        if x0 <= X <= x1 and y0 <= Y <= y1:
            return True
    return False


def seg_seg(s, t):
    (a, b), (c, d) = s, t

    def orient(p, q, r):
        return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])
    o1, o2 = orient(a, b, c), orient(a, b, d)
    o3, o4 = orient(c, d, a), orient(c, d, b)
    return o1 * o2 < 0 and o3 * o4 < 0


def orbit_cam(target, az, el, R=30.0):
    """A camera at azimuth az (degrees, from the -y axis towards +x) and
    elevation el, at distance R from the target."""
    a, e = math.radians(az), math.radians(el)
    eye = (target[0] + R * math.sin(a) * math.cos(e),
           target[1] - R * math.cos(a) * math.cos(e),
           target[2] + R * math.sin(e))
    return Camera(eye=eye, target=target, focal=R)


def fit(cam, pts, width):
    """Set the camera scale so that the points span the given width, and
    return the projected bounding box."""
    cam.scale = 1.0
    xs = [cam.project(p)[0][0] for p in pts]
    cam.scale = width / (max(xs) - min(xs))
    q = [cam.project(p)[0] for p in pts]
    return (min(a for a, b in q), min(b for a, b in q),
            max(a for a, b in q), max(b for a, b in q))


